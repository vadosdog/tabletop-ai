def прочитать_человека(путь: str, имена: list[str]) -> dict[str, dict[str, float]]:
    оценки: dict[str, dict[str, float]] = {}
    with Path(путь).open(encoding="utf-8") as ф:
        for строка in csv.DictReader(ф):
            имя = _опознать(строка.get("персонаж", ""), имена)
            критерий = (строка.get("критерий") or "").strip().lower()
            сырой = (строка.get("балл") or "").strip().replace(",", ".")
            if имя is None or критерий not in common.КРИТЕРИИ or not сырой:
                continue
            оценки.setdefault(имя, {})[критерий] = float(сырой)
    return оценки


def расхождение(таблица: dict, человек: dict) -> dict:
    """По каждому критерию отдельно: систематическое важнее случайного."""
    итог = {}
    for критерий in common.КРИТЕРИИ:
        разницы = []
        for имя, оценки in человек.items():
            судья = таблица.get(имя, {}).get("критерии", {}).get(критерий, {}).get("медиана")
            если_есть = оценки.get(критерий)
            if судья is None or если_есть is None:
                continue
            разницы.append(судья - если_есть)
        if not разницы:
            continue
        итог[критерий] = {
            "систематическое": round(statistics.fmean(разницы), 2),
            "случайное": round(statistics.fmean(abs(р) for р in разницы), 2),
            "пар": len(разницы),
        }
    return итог


