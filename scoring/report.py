# --- сведение оценок судьи -------------------------------------------------

def _опознать(сырое: str, имена: list[str]) -> str | None:
    ключ = (сырое or "").strip().lower()
    for имя in имена:
        if ключ.startswith(имя.lower()[:4]):
            return имя
    return None


def свести(судья: dict, имена: list[str], критерии: list[str] | None = None) -> dict:
    """Медиана трёх проходов и разброс между ними. Баллы без цитаты не в счёт."""
    критерии = критерии or common.КРИТЕРИИ
    собрано = {имя: {критерий: [] for критерий in критерии} for имя in имена}
    отброшено = {имя: 0 for имя in имена}
    штрафы_по_проходам = {имя: [] for имя in имена}
    все_штрафы = {имя: [] for имя in имена}

    for проход in судья["проходы"]:
        сумма_штрафов = {имя: 0 for имя in имена}
        for сырое_имя, данные in проход.get("персонажи", {}).items():
            имя = _опознать(сырое_имя, имена)
            if имя is None:
                continue
            for критерий, оценка in данные.get("критерии", {}).items():
                if критерий not in критерии:
                    continue
                if оценка.get("_засчитан"):
                    собрано[имя][критерий].append(int(оценка["балл"]))
                else:
                    отброшено[имя] += 1
            for штраф in данные.get("штрафы", []):
                if not штраф.get("_засчитан"):
                    continue
                вес = common.ШТРАФЫ.get(штраф.get("тип", ""), 0)
                сумма_штрафов[имя] += вес
                все_штрафы[имя].append({**штраф, "вес": вес, "проход": проход.get("_проход")})
        for имя in имена:
            штрафы_по_проходам[имя].append(сумма_штрафов[имя])

    таблица = {}
    for имя in имена:
        строка = {}
        сумма = 0
        for критерий in критерии:
            баллы = собрано[имя][критерий]
            медиана = statistics.median(баллы) if баллы else None
            строка[критерий] = {
                "медиана": медиана,
                "разброс": (max(баллы) - min(баллы)) if len(баллы) > 1 else 0,
                "проходы": баллы,
            }
            if медиана is not None:
                сумма += медиана
        штраф = statistics.median(штрафы_по_проходам[имя]) if штрафы_по_проходам[имя] else 0
        таблица[имя] = {
            "критерии": строка,
            "штраф": штраф,
            "штрафы_подробно": все_штрафы[имя],
            "баллов_без_цитаты": отброшено[имя],
            "итог": round(сумма + штраф, 1),
        }
    return таблица


