def калибровка(таблица: dict, контрольный: str | None, расхождения: dict,
               состав: dict | None = None) -> list[dict]:
    итоги = {имя: данные["итог"] for имя, данные in таблица.items()}
    низшие = ([имя for имя, б in итоги.items() if б == min(итоги.values())]
              if итоги else [])
    # Ничья внизу — это не «контрольный последний», это отсутствие сигнала.
    минимум = низшие[0] if len(низшие) == 1 else None
    разброс_итогов = round(max(итоги.values()) - min(итоги.values()), 1) if итоги else 0

    # Контрольный игрок имеет смысл только если он и правда на другой модели.
    модели = {имя: (состав or {}).get(имя, {}).get("модель") for имя in таблица}
    прочие = {м for имя, м in модели.items() if имя != контрольный and м}
    контроль_настоящий = bool(
        контрольный and модели.get(контрольный) and модели[контрольный] not in прочие
    )

    все_разбросы = [
        данные["критерии"][к]["разброс"]
        for данные in таблица.values() for к in common.КРИТЕРИИ
    ]
    стабильных = sum(1 for р in все_разбросы if р <= 1)
    доля = стабильных / len(все_разбросы) if все_разбросы else 0

    # Потолок: стабильность на максимуме — это не различающая способность.
    максимум = 5 * len(common.КРИТЕРИИ)
    на_потолке = sum(1 for б in итоги.values() if б >= максимум)
    оценки = [данные["критерии"][к]["медиана"]
              for данные in таблица.values() for к in common.КРИТЕРИИ]
    пятёрок = sum(1 for о in оценки if о == 5)
    всего_оценок = sum(1 for о in оценки if о is not None)

    есть_баллы = any(
        данные["критерии"][к]["медиана"] is not None
        for данные in таблица.values() for к in common.КРИТЕРИИ
    )
    if not есть_баллы:
        return [{
            "вопрос": "Калибровка",
            "ответ": "не считалась",
            "цифра": "отчёт собран без судьи (--judge не передан)",
            "вывод": "",
        }]

    пункты = [
        {
            "вопрос": "Баллы различаются?",
            "ответ": "да" if разброс_итогов > 1 else "нет",
            "цифра": f"разброс итогов {разброс_итогов}",
            "вывод": "" if разброс_итогов > 1 else "рубрика слепая, переписывать",
        },
        {
            "вопрос": "Контрольный игрок внизу?",
            "ответ": ("да" if контроль_настоящий and минимум == контрольный
                      else "нет" if контроль_настоящий else "нечего проверять"),
            "цифра": (
                f"контрольный {контрольный} на {модели.get(контрольный)}, низший балл у "
                + (минимум if минимум else f"ничья: {', '.join(низшие)}")
                if контроль_настоящий else
                (f"контрольный {контрольный} на той же модели, что и остальные — "
                 "слабого игрока в прогоне не было"
                 if контрольный else "контрольный игрок не назначен")
            ),
            "вывод": ("скоринг не измеряет качество игры"
                      if контроль_настоящий and минимум != контрольный else ""),
        },
        {
            "вопрос": "Рубрика различает?",
            "ответ": "нет" if на_потолке >= 2 else "да",
            "цифра": (f"на максимуме {на_потолке} из {len(таблица)} персонажей, "
                      f"пятёрок {пятёрок} из {всего_оценок}"),
            "вывод": ("рубрика упёрлась в потолок: сильных игроков она не "
                      "разводит, якоря на пятёрку надо поднимать"
                      if на_потолке >= 2 else ""),
        },
        {
            "вопрос": "Судья стабилен?",
            "ответ": "да" if доля > 0.5 else "нет",
            "цифра": f"разброс ≤1 у {стабильных} из {len(все_разбросы)} оценок",
            "вывод": "" if доля > 0.5 else "критерии сформулированы плохо",
        },
    ]

    if расхождения:
        плохие = [к for к, з in расхождения.items() if abs(з["систематическое"]) > 1]
        пункты.append({
            "вопрос": "Судья согласен с человеком?",
            "ответ": "нет" if плохие else "да",
            "цифра": "; ".join(
                f"{к}: систематическое {з['систематическое']:+}, случайное {з['случайное']}"
                for к, з in расхождения.items()
            ),
            "вывод": (f"переписать формулировки: {', '.join(плохие)}" if плохие else ""),
        })
    else:
        пункты.append({
            "вопрос": "Судья согласен с человеком?",
            "ответ": "не проверено",
            "цифра": "ручная оценка не подана (--human)",
            "вывод": "",
        })
    return пункты


