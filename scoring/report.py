def _клетка(значение) -> str:
    return "—" if значение is None else f"{значение:g}"


def _раздел_мастера(таблица_мастера: dict, судья_мастера: dict) -> list[str]:
    строки = _таблица_баллов(таблица_мастера, common.КРИТЕРИИ_МАСТЕРА,
                             "## Мастер")
    строки.insert(2, "Мастер — такой же участник эксперимента. Судья тот же и "
                     "так же слеп.")
    for имя, данные in таблица_мастера.items():
        for критерий in common.КРИТЕРИИ_МАСТЕРА:
            for проход in судья_мастера.get("проходы", []):
                оценка = (проход.get("персонажи", {}).get(имя, {})
                          .get("критерии", {}).get(критерий))
                if оценка and оценка.get("_засчитан"):
                    строки.append(
                        f"- {критерий}, балл {оценка['балл']}, круг "
                        f"{оценка.get('круг')} (проход {проход.get('_проход')}): "
                        f"«{оценка.get('цитата')}»"
                    )
    строки.append("")
    return строки


