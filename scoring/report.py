def _раздел_параметров(события) -> list[str]:
    """Условия сравнения. Самый важный блок в отчёте после баллов.

    Если у одной модели температура выше, а у другой лимит короче — сравниваются
    настройки, а не модели. Поэтому здесь и то, что задано всем, и то, что задать
    не удалось: замолчать второе значило бы соврать про первое.
    """
    блок = (_старт(события) or {}).get("параметры_генерации")
    if not блок:
        return []

    задано = блок.get("задано_всем", {})
    строки = ["## Условия сравнения", "",
              "Одно и то же у всех игроков, выставлено до первого хода:", "",
              "| Параметр | Значение |", "|---|---|"]
    подписи = {
        "температура": "температура",
        "top_p": "top_p",
        "предел_ответа_токенов": "предел ответа, токенов",
        "размышление": "режим размышления",
        "таймаут_с": "таймаут ответа, с",
        "попыток": "попыток при сбое сети",
    }
    for ключ, подпись in подписи.items():
        значение = задано.get(ключ)
        строки.append(f"| {подпись} | {'не задаётся' if значение is None else значение} |")

    словами = блок.get("размышление_словами_вендора") or {}
    if словами:
        строки += ["", "Режим размышления словами каждого вендора:", "",
                   "| Провайдер | Уровень |", "|---|---|"]
        for имя, уровень in sorted(словами.items()):
            строки.append(f"| {имя} | {уровень or '—'} |")
        строки += ["",
                   "Выключить размышление у всех нельзя: Gemini и Grok этого не умеют, "
                   "нижняя ступень у обоих — «low». Поэтому выровнялись по нижней общей "
                   "ступени. Одно и то же слово у разных вендоров означает разное число "
                   "токенов — доля размышления по каждому видна в таблице расхода.", ""]

    расхожд = блок.get("известные_расхождения") or {}
    if расхожд:
        строки += ["", "### Известные расхождения", "",
                   "Здесь всё, что выровнять не удалось. Это не оговорки задним "
                   "числом: список составлен до прогона и проверен живым запросом "
                   "к каждому API.", ""]
        for имя in sorted(расхожд):
            строки.append(f"**{имя}**")
            строки.append("")
            for пункт in расхожд[имя]:
                строки.append(f"- {пункт}")
            строки.append("")

    оговорка = блок.get("оговорка_о_детерминизме")
    if оговорка:
        строки += ["### Воспроизводимость", "", оговорка, ""]
    return строки + [""]


def _раздел_расхода(события) -> list[str]:
    """Сколько стоил прогон у кого, доля кэша и доля размышления."""
    итог = common.итог_прогона(события)
    по_провайдерам = итог.get("по_провайдерам") or {}
    if not по_провайдерам:
        return []

    строки = ["## Расход по провайдерам", "",
              "| Провайдер | Вход | Кэш | Доля кэша | Выход | Из них размышление | "
              "Повторов | Отказов | Деньги |",
              "|---|---|---|---|---|---|---|---|---|"]
    for имя in sorted(по_провайдерам):
        д = по_провайдерам[имя]
        доля_кэша = д.get("доля_кэша")
        размышление = д.get("размышление", 0)
        доля_р = д.get("доля_размышления")
        строки.append(
            f"| {имя} | {д.get('вход', 0)} | {д.get('кэш_чтение', 0)} | "
            f"{'—' if доля_кэша is None else f'{доля_кэша:.0%}'} | "
            f"{д.get('выход', 0)} | {размышление}"
            f"{'' if доля_р is None else f' ({доля_р:.0%})'} | "
            f"{д.get('повторов', '—')} | {д.get('отказов', 0)} | "
            f"${д.get('деньги_usd', 0):.4f} |"
        )

    строки += ["",
               "Токены размышления входят в выходные и по цене выхода же и считаются: "
               "второй раз за них не платят, в столбце они выделены только чтобы "
               "показать долю."]

    if "claude" in по_провайдерам:
        строки += ["",
                   "**Claude идёт по подписке.** Сумма в его строке — пересчёт по "
                   "публичным ставкам, который отдаёт SDK, а не счёт: по подписке "
                   "эти деньги не списывались. Суммы остальных трёх посчитаны по "
                   "ставкам из конфига и требуют сверки с настоящими счетами; сырые "
                   "токены лежат в логе, пересчёт не требует нового прогона."]

    обрывы = {и: д.get("обрывов_по_пределу") for и, д in по_провайдерам.items()
              if д.get("обрывов_по_пределу")}
    if обрывы:
        строки += ["", f"⚠️ Ответы, упёршиеся в предел длины: {обрывы}. "
                   "Такой ход обрезан на полуслове, и в сравнение его брать нельзя."]
    else:
        строки += ["", "Ни один ответ не упёрся в предел длины: лимит взят с запасом "
                   "и ни у кого не сработал, то есть на результат не повлиял."]

    выясненные = {и: д["расхождения_выясненные_на_ходу"]
                  for и, д in по_провайдерам.items()
                  if д.get("расхождения_выясненные_на_ходу")}
    if выясненные:
        строки += ["", "### Выяснилось по ходу прогона", ""]
        for имя in sorted(выясненные):
            for пункт in выясненные[имя]:
                строки.append(f"- **{имя}**: {пункт}")
        строки.append("")
    return строки + [""]


def _раздел_апстрима(события) -> list[str]:
    """Кто на самом деле обслуживал запросы через прослойку.

    Прямые подключения этого раздела не рождают: там вендор и есть исполнитель.
    А маршрутизатор вправе сменить хост, и если он это сделал, часть ходов
    сыграна на другой сборке — молчать об этом нельзя.
    """
    отметки = [е for е in события if е.get("тип_события") == "апстрим"]
    if not отметки:
        return []

    по_провайдерам: dict[str, list[dict]] = {}
    for отметка in отметки:
        по_провайдерам.setdefault(отметка.get("провайдер", "?"), []).append(отметка)

    строки = ["## Через прослойку", ""]
    for провайдер, список in sorted(по_провайдерам.items()):
        разрешённые = список[0].get("разрешённые") or []
        строки += [
            f"**{провайдер}** — разрешённые апстримы: "
            f"{', '.join(разрешённые) or '—'}, фолбэк запрещён.",
            "",
        ]
        if len(список) == 1:
            строки += [
                f"Весь прогон отвечал один апстрим: **{список[0].get('апстрим')}**. "
                "Закрепление удержалось, сборка не менялась.",
                "",
            ]
        else:
            цепочка = " → ".join(str(о.get("апстрим")) for о in список)
            строки += [
                f"⚠️ **Апстрим менялся посреди прогона:** {цепочка}.",
                "",
                "Смена произошла с круга "
                + ", ".join(str(о.get("круг")) for о in список[1:])
                + ". Ходы до и после смены сыграны на разных сборках, и "
                "сравнивать их между собой можно только с этой оговоркой.",
                "",
            ]
    return строки


def _раздел_ресурсов(события) -> list[str]:
    """Судьба, Удача, Стойкость, Решимость — заявлено против подтверждённого.

    Разница между колонками — не придирка, а суть: в прошлых прогонах Удачи
    в коде не было вовсе, игроки её «тратили», и судья засчитывал это за
    работу с механикой. Пока эти два числа не стоят рядом, балл по «Правилам»
    ничего не значит.
    """
    итог = common.итог_прогона(события)
    ресурсы = итог.get("ресурсы") or {}
    if not ресурсы:
        return []

    строки = ["## Ресурсы", "",
              "| Игрок | Заявлено | Подтверждено | Решимость начислена | "
              "Провалов можно было перебросить | На финише |",
              "|---|---|---|---|---|---|"]
    for имя, д in ресурсы.items():
        финиш = д.get("на_финише") or {}
        осталось = (f"Судьба {финиш.get('судьба', '?')}, "
                    f"Удача {финиш.get('удача', '?')}/{финиш.get('удача_макс', '?')}, "
                    f"Стойкость {финиш.get('стойкость', '?')}, "
                    f"Решимость {финиш.get('решимость', '?')}/"
                    f"{финиш.get('решимость_макс', '?')}")
        заявлено = ", ".join(f"{к} ×{v}" for к, v in (д.get("заявлено") or {}).items())
        подтверждено = ", ".join(f"{к} ×{v}" for к, v in
                                 (д.get("подтверждено") or {}).items())
        строки.append(
            f"| {имя} | {заявлено or '—'} | {подтверждено or '—'} | "
            f"{д.get('решимость_начислена', 0)} | "
            f"{д.get('провалов_можно_было_перебросить', 0)} | {осталось} |"
        )

    расхождения = [
        (имя, д) for имя, д in ресурсы.items()
        if (д.get("заявлено") or {}) != (д.get("подтверждено") or {})
    ]
    if расхождения:
        строки += ["", "### Заявлено, но не подтверждено", "",
                   "Игрок объявил трату, скрипт её не принял. Либо тратить было "
                   "нечего, либо это баг — и то и другое надо видеть. "
                   "**Судье такие заявки за трату не засчитываются.**", ""]
        отклонены = [е for е in события if е.get("тип_события") == "ресурс"
                     and е.get("заявлено") and not е.get("подтверждено")
                     and not е.get("ожидание")]
        for событие in отклонены:
            причина = событие.get("причина") or "без объяснения"
            строки.append(f"- круг {событие.get('круг')}, **{событие.get('кто')}**, "
                          f"{событие.get('ресурс')}: {причина}")
        if not отклонены:
            строки.append("- отклонённых заявок нет")
        строки.append("")

        # Заявка на Удачу живёт один круг: не подвернулось провала — сгорела.
        # Это не отказ скрипта, а промах игрока по времени, и путать их нельзя.
        сгорели = [е for е in события if е.get("тип_события") == "ресурс"
                   and е.get("ожидание")]
        if сгорели:
            строки += ["Заявки на Удачу, принятые в ожидание (сработали бы на "
                       "первом же проваленном броске того же круга):", ""]
            for е in сгорели:
                строки.append(f"- круг {е.get('круг')}, **{е.get('кто')}**")
            строки.append("")

    перебросы = [е for е in события if е.get("тип_события") == "ресурс"
                 and е.get("бросок_до")]
    if перебросы:
        строки += ["### Перебросы за Удачу", "",
                   "| Круг | Игрок | Было | Стало | Помогло |", "|---|---|---|---|---|"]
        for е in перебросы:
            до, после = е["бросок_до"], е["бросок_после"]
            строки.append(
                f"| {е.get('круг')} | {е.get('кто')} | {до['выпало']} из {до['цель']} | "
                f"{после['выпало']} из {после['цель']} | "
                f"{'да' if е.get('помогло') else 'нет'} |"
            )
        строки.append("")

    без_трат = [имя for имя, д in ресурсы.items()
                if not (д.get("подтверждено") or {})
                and д.get("провалов_можно_было_перебросить", 0) > 0]
    if без_трат:
        строки += ["", "Доиграли с полными руками, имея возможность потратить: "
                   + ", ".join(без_трат) + ". Число провалов в таблице показывает, "
                   "сколько раз случай был — без него упрёк был бы несправедлив.", ""]
    return строки + [""]


def _раздел_отказов(события) -> list[str]:
    """Счётчик отказов по каждому игроку с цитатой.

    Ноль здесь значит ровно то, что написано, только если ловля проверена
    искусственным отказным запросом. Ссылка на эту проверку — ниже таблицы.
    """
    итог = common.итог_прогона(события)
    отказы = итог.get("отказы") or []

    подозрения = [
        е for е in события
        if е.get("тип_события") == "ход"
        and "подозрение_на_отказ" in (е.get("метки") or [])
    ]

    строки = ["## Отказы моделей", ""]
    if not отказы:
        строки += ["Ни одна модель не отказалась играть сцену.", ""]
    else:
        по_игрокам: dict[str, int] = {}
        for запись in отказы:
            по_игрокам[запись["кто"]] = по_игрокам.get(запись["кто"], 0) + 1
        строки += ["| Игрок | Провайдер | Отказов |", "|---|---|---|"]
        провайдеры_игроков = {з["кто"]: з.get("провайдер", "?") for з in отказы}
        for имя in sorted(по_игрокам):
            строки.append(
                f"| {имя} | {провайдеры_игроков.get(имя, '?')} | {по_игрокам[имя]} |"
            )
        строки += ["", "### Цитаты", ""]
        for запись in отказы:
            строки.append(
                f"- круг {запись.get('круг', '?')}, **{запись['кто']}** "
                f"({запись.get('провайдер', '?')}): «{запись['цитата']}»"
            )
        строки += ["",
                   "Отказ не повторялся: тихий ретрай спрятал бы его. Персонаж "
                   "считался промолчавшим, круг шёл дальше, текст отказа за стол "
                   "не уходил — ни мастер, ни другие игроки его не видели.", ""]

    if подозрения:
        строки += [f"Кроме того, {len(подозрения)} ответ(ов) помечено подозрением "
                   "на отказ — их надо прочитать глазами, автомат в них не уверен:", ""]
        for событие in подозрения:
            цитата = " ".join((событие.get("текст") or "").split())[:200]
            строки.append(f"- круг {событие.get('круг', '?')}, "
                          f"**{событие.get('говорящий')}**: «{цитата}»")
        строки.append("")

    строки += ["Ловля отказов проверена отдельно: искусственный отказный запрос "
               "к каждому провайдеру (`проверка.py --отказ`) и прогон на подделке "
               "(`tests/test_отказ_в_прогоне.py`). Без этого ноль в таблице значил "
               "бы и «никто не отказался», и «мы не умеем ловить».", ""]
    return строки


def собрать_отчёт(события, таблица, счётчики, пункты, расхождения, судья,
                  таблица_мастера=None, судья_мастера=None, раскрытие=None) -> str:
    имена = list(таблица)
    итог_прогона = common.итог_прогона(события)
    состав = common.состав(события)
    контрольный = common.контрольный(события)

    строки = ["# Отчёт по репетиционному прогону", ""]

    строки += ["## Прогон", ""]
    строки += [
        f"- кругов: {итог_прогона.get('кругов', '?')}, остановка: "
        f"{итог_прогона.get('остановка', '?')}",
        f"- по часам: {итог_прогона.get('минут', '?')} мин",
        f"- токенов: {итог_прогона.get('токенов', {})}, "
        f"стоимость ${итог_прогона.get('стоимость_usd', 0)}",
        f"- бросков: {итог_прогона.get('бросков', '?')}, зерно "
        f"{итог_прогона.get('зерно', '?')} (прогон воспроизводится)",
        f"- судья: {судья.get('модель_судьи')}, проходов {судья.get('проходов')}"
        + (f", по выборке кругов {судья.get('круги')}" if судья.get("круги") else "")
        if судья.get("проходы") else "- судья: не запускался",
        "",
    ]

    строки += ["## Кто за кого играл", "",
               "| Персонаж | Провайдер | Модель |", "|---|---|---|"]
    for имя, настройки in состав.items():
        пометка = " ← контрольный" if имя == контрольный else ""
        строки.append(
            f"| {имя}{пометка} | {настройки.get('провайдер')} | {настройки.get('модель')} |"
        )
    строки += ["", "Судье этой таблицы не показывали.", ""]

    if not судья.get("проходы"):
        строки += ["## Баллы", "",
                   "Судья не запускался: отчёт собран по логу. "
                   "Таблица баллов появится после `judge.py`.", ""]
    else:
        строки += _таблица_баллов(таблица)

    if таблица_мастера:
        строки += _раздел_мастера(таблица_мастера, судья_мастера or {})
    if раскрытие:
        строки += _раздел_раскрытия(раскрытие)

    строки += _хвост_отчёта(таблица, счётчики, пункты, расхождения, судья)
    строки += _раздел_ресурсов(события)
    строки += _раздел_параметров(события)
    строки += _раздел_апстрима(события)
    строки += _раздел_отказов(события)
    строки += _раздел_расхода(события)
    строки += _раздел_боя(события)
    строки += _раздел_разгона(события)
    return "\n".join(строки).strip() + "\n"


def _таблица_баллов(таблица: dict, критерии: list[str] | None = None,
                    заголовок: str = "## Баллы") -> list[str]:
    критерии = критерии or common.КРИТЕРИИ
    имена = list(таблица)
    строки = [заголовок, "",
               "Медиана трёх проходов, в скобках разброс между проходами.", "",
               "| Персонаж | " + " | ".join(c.capitalize() for c in критерии)
               + " | Штрафы | Итог |",
               "|---" * (len(критерии) + 3) + "|"]
    for имя in имена:
        клетки = []
        for критерий in критерии:
            данные = таблица[имя]["критерии"][критерий]
            клетки.append(f"{_клетка(данные['медиана'])} ({данные['разброс']})")
        строки.append(
            f"| {имя} | " + " | ".join(клетки)
            + f" | {таблица[имя]['штраф']:g} | **{таблица[имя]['итог']:g}** |"
        )
    строки.append("")

    отброшено = {имя: таблица[имя]["баллов_без_цитаты"] for имя in имена}
    if any(отброшено.values()):
        строки += [
            "Баллов отброшено за ненайденную цитату: "
            + ", ".join(f"{имя} — {n}" for имя, n in отброшено.items() if n),
            "",
        ]
    return строки


def _хвост_отчёта(таблица, счётчики, пункты, расхождения, судья) -> list[str]:
    имена = list(таблица)
    строки = ["## Без баллов, но в таблицу", "",
               "| Персонаж | Кругов отыграл | Тайных ходов | Средняя длина реплики | "
               "Обратились | Ответил | Самобросков |",
               "|---|---|---|---|---|---|---|"]
    for имя in имена:
        м = счётчики[имя]
        строки.append(
            f"| {имя} | {м.get('кругов_отыграл', м['ходов'])} | {м['тайных_ходов']} | "
            f"{м['средняя_длина_реплики']} | {м['обратились_к_нему']} | "
            f"{м['ответил']} | {м['самобросков']} |"
        )
    строки += ["", "«Обратились» и «ответил» считаются по упоминанию имени — "
                   "это эвристика, а не точный счёт.", ""]

    строки += ["## Калибровка", ""]
    for пункт in пункты:
        хвост = f" — {пункт['вывод']}" if пункт["вывод"] else ""
        строки.append(f"- **{пункт['вопрос']}** {пункт['ответ'].upper()}. "
                      f"{пункт['цифра']}{хвост}")
    строки.append("")

    if расхождения:
        строки += ["## Расхождение судьи и человека", "",
                   "| Критерий | Систематическое | Случайное | Пар |",
                   "|---|---|---|---|"]
        for критерий, данные in расхождения.items():
            строки.append(
                f"| {критерий} | {данные['систематическое']:+g} | "
                f"{данные['случайное']:g} | {данные['пар']} |"
            )
        строки += ["", "Положительное систематическое — судья щедрее человека.", ""]

    if not судья.get("проходы"):
        return строки

    строки += ["## Цитаты — заготовка монтажного листа", ""]
    for имя in имена:
        строки.append(f"### {имя}")
        for критерий in common.КРИТЕРИИ:
            for проход in судья["проходы"]:
                for сырое, данные in проход.get("персонажи", {}).items():
                    if _опознать(сырое, имена) != имя:
                        continue
                    оценка = данные.get("критерии", {}).get(критерий)
                    if not оценка or not оценка.get("_засчитан"):
                        continue
                    строки.append(
                        f"- {критерий}, балл {оценка['балл']}, круг "
                        f"{оценка.get('круг')} (проход {проход.get('_проход')}, "
                        f"цитата {оценка.get('_цитата')}): «{оценка.get('цитата')}»"
                    )
        for штраф in таблица[имя]["штрафы_подробно"]:
            строки.append(
                f"- ШТРАФ {штраф.get('тип')} ({штраф.get('вес')}), круг "
                f"{штраф.get('круг')}: «{штраф.get('цитата')}»"
            )
        строки.append("")

    return строки


def main() -> int:
    разбор = argparse.ArgumentParser(description="Сводный отчёт по прогону")
    разбор.add_argument("--log", required=True, nargs="+",
                        help="один лог или несколько подряд (продолженный прогон)")
    разбор.add_argument("--judge", default=None,
                        help="оценки судьи; без них будут транскрипт и счётчики")
    разбор.add_argument("--out", required=True)
    разбор.add_argument("--human", default=None, help="CSV с ручными оценками")
    разбор.add_argument("--judge-sample", default=None,
                        help="оценки судьи по той же выборке, что у человека")
    разбор.add_argument("--judge-gm", default=None,
                        help="оценки мастера (judge.py --rubric rubric-gm.md)")
    разбор.add_argument("--reveal", default=None,
                        help="раскрытие ваншота (reveal.py)")
    аргументы = разбор.parse_args()

    события = common.прочитать_лог(аргументы.log)
    имена = common.персонажи(события)
    if аргументы.judge:
        судья = json.loads(Path(аргументы.judge).read_text(encoding="utf-8"))
    else:
        # Без судьи отчёт всё равно нужен: транскрипт, счётчики, время, расход.
        судья = {"проходы": [], "проходов": 0, "модель_судьи": None, "круги": None}

    таблица = свести(судья, имена)
    счётчики = metrics.посчитать(события, имена)

    расхождения = {}
    if аргументы.human:
        человек = прочитать_человека(аргументы.human, имена)
        источник = таблица
        if аргументы.judge_sample:
            выборочный = json.loads(Path(аргументы.judge_sample).read_text(encoding="utf-8"))
            источник = свести(выборочный, имена)
        расхождения = расхождение(источник, человек)

    таблица_мастера = судья_мастера = раскрытие = None
    if аргументы.judge_gm:
        судья_мастера = json.loads(Path(аргументы.judge_gm).read_text(encoding="utf-8"))
        таблица_мастера = свести(судья_мастера, ["Мастер"], common.КРИТЕРИИ_МАСТЕРА)
    if аргументы.reveal:
        раскрытие = json.loads(Path(аргументы.reveal).read_text(encoding="utf-8"))

    пункты = калибровка(таблица, common.контрольный(события), расхождения,
                        common.состав(события))

    папка = Path(аргументы.out)
    папка.mkdir(parents=True, exist_ok=True)

    (папка / "отчёт.md").write_text(
        собрать_отчёт(события, таблица, счётчики, пункты, расхождения, судья,
                      таблица_мастера, судья_мастера, раскрытие),
        encoding="utf-8",
    )
    (папка / "транскрипт.md").write_text(
        common.транскрипт(события, слепой=False), encoding="utf-8"
    )
    (папка / "транскрипт-слепой.md").write_text(
        common.транскрипт(события, слепой=True), encoding="utf-8"
    )
    (папка / "баллы.json").write_text(
        json.dumps({"баллы": таблица, "мастер": таблица_мастера,
                    "счётчики": счётчики, "калибровка": пункты,
                    "расхождение": расхождения,
                    "раскрытие": (раскрытие or {}).get("_свод"),
                    "бой": common.бой(события),
                    "разгон": common.разгон(события)},
                   ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    with (папка / "баллы.csv").open("w", encoding="utf-8", newline="") as ф:
        писарь = csv.writer(ф)
        писарь.writerow(["персонаж"] + common.КРИТЕРИИ
                        + [f"разброс_{к}" for к in common.КРИТЕРИИ] + ["штраф", "итог"])
        for имя, данные in таблица.items():
            писарь.writerow(
                [имя]
                + [данные["критерии"][к]["медиана"] for к in common.КРИТЕРИИ]
                + [данные["критерии"][к]["разброс"] for к in common.КРИТЕРИИ]
                + [данные["штраф"], данные["итог"]]
            )

    print(f"отчёт: {папка / 'отчёт.md'}")
    for пункт in пункты:
        print(f"  {пункт['вопрос']:35} {пункт['ответ'].upper():14} {пункт['цифра']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
