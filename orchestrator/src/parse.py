"""Разбор реплик. Скрипт ничего не редактирует — только читает служебные метки.

Единственное исключение из «не редактируем» — служебные теги режима и блоки
«ТОЛЬКО ДЛЯ», которые вырезаются из текста для игроков: это канал управления,
а не реплика мастера.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from . import protocol

# Русские слова протокола — из protocol.py. Здесь только то, как они обёрнуты
# в разметку: скобки, двоеточия, звёздочки markdown, которыми модель их метит.
РЕЖИМЫ = protocol.MODES

_ТЕГ_РЕЖИМА = re.compile(
    rf"\[\s*{protocol.TAG_MODE}\s*:\s*({'|'.join(protocol.MODES)})\s*\]", re.IGNORECASE
)
_ТЕГ_ФИНАЛА = re.compile(rf"\[\s*{protocol.TAG_FINALE}\s*\]", re.IGNORECASE)
_ТЕГ_ВЫБЫЛ = re.compile(
    rf"\[\s*{protocol.TAG_DOWN}\s*:\s*(?P<имя>[^,\]]+?)\s*(?:,\s*(?P<причина>[^\]]+?))?\s*\]",
    re.IGNORECASE,
)
_ТЕГ_ВЕРНУЛСЯ = re.compile(
    rf"\[\s*{protocol.TAG_BACK}\s*:\s*(?P<имя>[^,\]]+?)\s*(?:,[^\]]*)?\]", re.IGNORECASE
)
_СТРОКА_ПРОВЕРКИ = re.compile(
    rf"^[ \t>*_]*{protocol.LINE_CHECK}[ \t]*[*_]*[ \t]*:[ \t]*(?P<тело>.+?)[ \t]*$",
    re.IGNORECASE | re.MULTILINE,
)
_ЗАГОЛОВОК_ЛИЧНОГО = re.compile(
    r"^[ \t>*_#]*" + r"[ \t]+".join(protocol.HEADER_PRIVATE.split())
    + r"[ \t]*:?[ \t]*\[?[ \t]*(?P<имя>[А-ЯЁа-яё]+)[^\n]*$",
    re.IGNORECASE | re.MULTILINE,
)
_ТАЙНО = re.compile(rf"^[ \t>*_#]*{protocol.MARK_SECRET}\b[ \t]*:?", re.IGNORECASE)
_СТРОКА_АТАКИ = re.compile(
    rf"^[ \t>*_]*{protocol.LINE_ATTACK}[ \t]*[*_]*[ \t]*:[ \t]*(?P<тело>.+?)[ \t]*$",
    re.IGNORECASE | re.MULTILINE,
)
_СТРЕЛКА = re.compile(r"\s*(?:→|->|–>|=>|➔)\s*")

# Модель, назвавшая число броска сама. Ловим цифру рядом с «бросковым» словом
# в пределах одного предложения: в прозе этого мира цифры почти не встречаются.
_БРОСКОВЫЕ_СЛОВА = (
    r"бросок|броск\w+|выпал\w*|выпад\w*|кида\w+|кину\w+|кинул\w*|"
    r"результат\w*|сотн\w+|д100|d100|цель\w*|целев\w+"
)
_САМОБРОСОК = [
    re.compile(rf"(?:{_БРОСКОВЫЕ_СЛОВА})[^.!?\n]{{0,25}}?\b(\d{{1,3}})\b", re.IGNORECASE),
    re.compile(rf"\b(\d{{1,3}})\b[^.!?\n]{{0,25}}?(?:{_БРОСКОВЫЕ_СЛОВА})", re.IGNORECASE),
    re.compile(r"уровн\w+\s+успеха\s*[:—–-]?\s*([+-]?\d{1,2})", re.IGNORECASE),
]


@dataclass
class Атака:
    кто: str
    по_кому: str
    чем: str
    защита: str | None = None
    строка: str = ""
    метки: list[str] = field(default_factory=list)


@dataclass
class Проверка:
    персонаж: str
    навык: str
    сложность: str
    строка: str
    метки: list[str] = field(default_factory=list)
    база: int | None = None   # мастер задал целевое число NPC прямо в строке


def режим(текст: str, по_умолчанию: str = protocol.TALK) -> tuple[str, bool]:
    """Последний тег режима в реплике. Второе значение — был ли тег вообще."""
    найдено = _ТЕГ_РЕЖИМА.findall(текст)
    if not найдено:
        return по_умолчанию, False
    return найдено[-1].upper(), True


def без_служебных_тегов(текст: str) -> str:
    """Убирает [РЕЖИМ: …], [ФИНАЛ] и [РЕШИМОСТЬ: …] — это канал управления.

    Теги выбытия и возвращения остаются в тексте: для игроков это событие
    сцены, а не служебная разметка. «Курта увели» партия должна прочитать.
    А вот начисление Решимости за столом не звучит: игрок узнаёт о нём
    отдельной служебной строкой, вместе с новым остатком.
    """
    чистый = _ТЕГ_РЕШИМОСТЬ.sub("", _ТЕГ_ФИНАЛА.sub("", _ТЕГ_РЕЖИМА.sub("", текст)))
    return re.sub(r"\n{3,}", "\n\n", чистый).strip()


def объявлен_финал(текст: str) -> bool:
    return bool(_ТЕГ_ФИНАЛА.search(текст))


def _чистое_имя(сырое: str, известные: list[str]) -> tuple[str, int | None, list[str]]:
    """Имя, явно указанная база и метки.

    Мастер вправе кидать за персонажей мира. Для них он либо опирается на
    карточку из конфига, либо пишет целевое число прямо в строке:
    «ПРОВЕРКА: Сержант (45), Обаяние, трудно». Число — это характеристика NPC,
    а не бросок, называть её мастеру не запрещено.
    """
    имя = re.sub(r"[\[\]*_«»\"'.]", "", сырое).strip()
    база = None
    явная = re.search(r"\((\d{1,3})\)", имя)
    if явная:
        база = int(явная.group(1))
        имя = имя[: явная.start()].strip()

    первое = имя.split()[0] if имя.split() else имя
    for известное in известные:
        if первое.lower().startswith(известное.lower()[:4]):
            return известное, база, []
    return имя, база, ["проверка_за_нпс"]


def проверки(текст: str, известные: list[str]) -> tuple[list[Проверка], list[str]]:
    """Все строки «ПРОВЕРКА: …». Вторым значением — метки аномалий."""
    найденные: list[Проверка] = []
    аномалии: list[str] = []

    for совпадение in _СТРОКА_ПРОВЕРКИ.finditer(текст):
        тело = совпадение.group("тело").strip().rstrip("*_ ")
        части = [ч.strip() for ч in тело.split(",") if ч.strip()]
        строка = совпадение.group(0).strip()

        if len(части) < 2:
            аномалии.append("непарсимая_проверка")
            continue

        имя, база, метки = _чистое_имя(части[0], известные)
        навык = re.sub(r"[\[\]*_]", "", части[1]).strip()
        if len(части) >= 3:
            сложность = re.sub(r"[\[\]*_]", "", части[2]).strip()
        else:
            сложность = "испытание"
            метки.append("сложность_не_указана")
        if len(части) > 3:
            метки.append("лишние_поля_в_проверке")

        аномалии.extend(метки)
        найденные.append(Проверка(имя, навык, сложность, строка, метки, база))

    return найденные, аномалии


def атаки(текст: str, известные: list[str]) -> tuple[list[Атака], list[str]]:
    """Строки «АТАКА: кто → по кому, чем [, защита]»."""
    найденные: list[Атака] = []
    аномалии: list[str] = []

    for совпадение in _СТРОКА_АТАКИ.finditer(текст):
        тело = совпадение.group("тело").strip().rstrip("*_ ")
        стороны = _СТРЕЛКА.split(тело, maxsplit=1)
        if len(стороны) != 2:
            аномалии.append("непарсимая_атака")
            continue

        кто, _, метки_кто = _чистое_имя(стороны[0], известные)
        части = [ч.strip() for ч in стороны[1].split(",") if ч.strip()]
        if not части:
            аномалии.append("непарсимая_атака")
            continue

        по_кому, _, метки_цели = _чистое_имя(части[0], известные)
        чем = re.sub(r"[\[\]*_]", "", части[1]).strip() if len(части) > 1 else "кулаки"
        защита = части[2] if len(части) > 2 else None
        if len(части) > 3:
            аномалии.append("лишние_поля_в_атаке")

        метки = [м for м in метки_кто + метки_цели if м != "проверка_за_нпс"]
        найденные.append(Атака(кто, по_кому, чем, защита,
                               совпадение.group(0).strip(), метки))
        аномалии.extend(метки)

    return найденные, аномалии


def подписать_атаки(текст: str, итоги: dict[str, str]) -> str:
    """Дописывает исход к строке атаки. Только для лога и мастера."""
    def замена(совпадение: re.Match) -> str:
        строка = совпадение.group(0).rstrip()
        итог = итоги.get(строка.strip())
        return f"{строка} → {итог}" if итог else строка

    return _СТРОКА_АТАКИ.sub(замена, текст)


def без_строк_атак(текст: str) -> str:
    """Вырезает строки атак из текста для игроков.

    Игрок видит свои раны цифрами и чужие — только со стороны. Строка атаки с
    подписанным исходом выдала бы всем точный остаток ран каждого, а это ровно
    то, чего быть не должно. Само действие мастер описывает словами в сцене.
    """
    чистый = _СТРОКА_АТАКИ.sub("", текст)
    return re.sub(r"\n{3,}", "\n\n", чистый).strip()


def разделить_личное(текст: str) -> tuple[str, dict[str, str]]:
    """Делит реплику мастера на публичную часть и блоки «ТОЛЬКО ДЛЯ имя»."""
    заголовки = list(_ЗАГОЛОВОК_ЛИЧНОГО.finditer(текст))
    if not заголовки:
        return текст.strip(), {}

    публично = текст[: заголовки[0].start()].strip()
    личное: dict[str, str] = {}
    for i, заголовок in enumerate(заголовки):
        конец = заголовки[i + 1].start() if i + 1 < len(заголовки) else len(текст)
        кусок = текст[заголовок.end(): конец].strip()
        имя = заголовок.group("имя").capitalize()
        личное[имя] = (личное.get(имя, "") + "\n\n" + кусок).strip() if имя in личное else кусок
    return публично, личное


# «ТРАЧУ УДАЧУ» в ходе игрока. Допускаем падежи и разделители: модель пишет
# то «ТРАЧУ УДАЧУ», то «Трачу Удачу,», то «трачу решимость —».
_ТРАТА = re.compile(
    rf"\bтрач[уy]\s+(?P<ресурс>{protocol.alternation(protocol.RESOURCE_STEMS)})",
    re.IGNORECASE,
)

# «[РЕШИМОСТЬ: Ханна, +1, вступилась за Йорга против патруля]»
_ТЕГ_РЕШИМОСТЬ = re.compile(
    rf"\[\s*{protocol.TAG_RESOLVE}\s*:\s*(?P<имя>[^,\]]+)\s*,\s*\+?(?P<сколько>\d+)\s*"
    r"(?:,\s*(?P<причина>[^\]]*))?\]",
    re.IGNORECASE,
)

_РЕСУРС_К_ИМЕНИ = protocol.RESOURCE_STEMS


# «ТРАЧУ СУДЬБУ, беру 01» — игрок в безнадёжном положении называет значение сам.
_ВЫБРАННОЕ_ЧИСЛО = re.compile(
    rf"трач[уy]\s+{protocol.STEM_FATE}\w*[^.\n]{{0,40}}?\b(?P<число>100|\d{{1,2}})\b",
    re.IGNORECASE)


# Слово, в котором кириллица перемешана с латиницей. Самая коварная порча
# текста: «сcылка» с латинской c выглядит как обычное слово, но это уже не
# русский. Такие подмены глазом не ловятся, а на экране остаются навсегда.
_СМЕШАННОЕ_СЛОВО = re.compile(r"\b(?=\w*[а-яёА-ЯЁ])(?=\w*[a-zA-Z])\w+\b")
_КИРИЛЛИЦА_В_СЛОВЕ = re.compile(r"[а-яёА-ЯЁ]")
_ЛАТИНИЦА_В_СЛОВЕ = re.compile(r"[a-zA-Z]")


def порча_языка(текст: str) -> dict:
    """Чем испорчен русский текст: чужими словами и подменёнными буквами.

    Считается по каждой реплике и уходит судье как минус модели. Две разные
    беды: целиком нерусская реплика — это одно, а латинская «c» посреди
    русского слова — другое, и второе опаснее, потому что незаметно.
    """
    смешанные = [с for с in _СМЕШАННОЕ_СЛОВО.findall(текст)
                 # Слово из одной латинской буквы среди кириллицы — не порча,
                 # а обычная скобка вроде «пункт a»; порча — это буква ВНУТРИ.
                 if len(_ЛАТИНИЦА_В_СЛОВЕ.findall(с)) < len(с)
                 and len(_КИРИЛЛИЦА_В_СЛОВЕ.findall(с)) < len(с)]
    кириллицы = len(_КИРИЛЛИЦА_В_СЛОВЕ.findall(текст))
    латиницы = len(_ЛАТИНИЦА_В_СЛОВЕ.findall(текст))
    целиком_чужой = латиницы > 20 and латиницы > кириллицы * 3
    return {
        "смешанные_слова": сортировать_уникальные(смешанные),
        "целиком_не_по_русски": целиком_чужой,
        "испорчено": bool(смешанные) or целиком_чужой,
    }


def сортировать_уникальные(слова: list[str]) -> list[str]:
    видел, итог = set(), []
    for слово in слова:
        ключ = слово.lower()
        if ключ not in видел:
            видел.add(ключ)
            итог.append(слово)
    return итог


def выбранное_значение(текст: str, по_умолчанию: int = 1) -> int:
    """Какое число игрок взял себе за Судьбу. Не назвал — берём лучшее.

    Лучшее это 01: автоуспех по правилам. Молчание игрока разумнее трактовать
    в его пользу, чем гадать: он и так заплатил постоянным ресурсом.
    """
    совпадение = _ВЫБРАННОЕ_ЧИСЛО.search(текст)
    if not совпадение:
        return по_умолчанию
    return max(1, min(100, int(совпадение.group("число"))))


def траты(текст: str) -> list[str]:
    """Какие ресурсы игрок заявил к трате. Порядок сохраняется, дубли — нет.

    Заявка — это ещё не трата: списывает её скрипт и только если есть чем.
    Именно на этом различии сгорел прошлый прогон, где судья зачёл за трату
    слова «Трачу Удачу», не подкреплённые ничем.
    """
    найдено: list[str] = []
    for совпадение in _ТРАТА.finditer(текст):
        сырое = совпадение.group("ресурс").lower()
        for корень, имя in _РЕСУРС_К_ИМЕНИ.items():
            if сырое.startswith(корень) and имя not in найдено:
                найдено.append(имя)
                break
    return найдено


def начисления_решимости(текст: str, известные: list[str]) -> list[dict]:
    """Теги [РЕШИМОСТЬ: имя, +1, причина] из сцены мастера."""
    найдено = []
    for совпадение in _ТЕГ_РЕШИМОСТЬ.finditer(текст):
        имя, _, метки = _чистое_имя(совпадение.group("имя"), известные)
        найдено.append({
            "имя": имя,
            "сколько": int(совпадение.group("сколько")),
            "причина": (совпадение.group("причина") or "").strip() or "не указана",
            "метки": метки,
            "строка": совпадение.group(0),
        })
    return найдено


def выбытия(текст: str, известные: list[str]) -> list[tuple[str, str]]:
    """Кого мастер вывел из игры и почему. Имя опознаётся по списку игроков."""
    найдено = []
    for совпадение in _ТЕГ_ВЫБЫЛ.finditer(текст):
        имя, _, метки = _чистое_имя(совпадение.group("имя"), известные)
        причина = (совпадение.group("причина") or "не указана").strip()
        if метки:
            причина += " (имя не опознано)"
        найдено.append((имя, причина))
    return найдено


def возвращения(текст: str, известные: list[str]) -> list[str]:
    имена = []
    for совпадение in _ТЕГ_ВЕРНУЛСЯ.finditer(текст):
        имя, _, _ = _чистое_имя(совпадение.group("имя"), известные)
        имена.append(имя)
    return имена


def тайный_ход(текст: str) -> bool:
    return bool(_ТАЙНО.match(текст.lstrip()))


def самоброски(текст: str, известные: set[int] | None = None) -> list[str]:
    """Фрагменты, в которых модель назвала число броска сама.

    `известные` — числа, которые скрипт уже выдал сам (выпавшие и целевые).
    Их пересказ не самоброс: мастер вправе назвать результат, который получил.
    """
    известные = известные or set()
    найдено: list[str] = []
    for шаблон in _САМОБРОСОК:
        for совпадение in шаблон.finditer(текст):
            try:
                число = int(совпадение.group(1))
            except (IndexError, ValueError):
                число = None
            if число is not None and число in известные:
                continue
            фрагмент = совпадение.group(0).strip()
            if фрагмент not in найдено:
                найдено.append(фрагмент)
    return найдено


def подписать_проверки(текст: str, броски: dict[str, str]) -> str:
    """Дописывает результат броска прямо к строке проверки — для глаз игроков."""
    def замена(совпадение: re.Match) -> str:
        строка = совпадение.group(0).rstrip()
        итог = броски.get(строка.strip())
        return f"{строка} → {итог}" if итог else строка

    return _СТРОКА_ПРОВЕРКИ.sub(замена, текст)
