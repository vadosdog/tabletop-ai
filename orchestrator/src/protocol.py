# Режимы сцены. Мастер объявляет тегом [РЕЖИМ: …].
TALK = "РАЗГОВОР"
ACTION = "ДЕЙСТВИЕ"
MODES = (TALK, ACTION)
DEFAULT_MODE = TALK

# Служебные теги мастера: канал управления, а не реплика. Теги режима, финала
# и решимости вырезаются из текста, который уходит игрокам.
TAG_MODE = "РЕЖИМ"
TAG_FINALE = "ФИНАЛ"
TAG_DOWN = "ВЫБЫЛ"
TAG_BACK = "ВЕРНУЛСЯ"
TAG_RESOLVE = "РЕШИМОСТЬ"

# Строки, которые мастер пишет отдельной строкой, а скрипт по ним работает.
LINE_CHECK = "ПРОВЕРКА"
LINE_ATTACK = "АТАКА"

# Заголовок личного блока: текст под ним видит только названный игрок.
