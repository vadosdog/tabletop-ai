"""Русский игровой протокол — единственное место, где кириллица нарочно.

Всё в этом модуле модели либо видят в промпте, либо произносят в ответ, и
скрипт вылавливает это из русского текста регулярками. Перевести здесь хоть
слово — значит поставить другой эксперимент: промпты, карточки персонажей и
рубрика судьи написаны по-русски и на эти же слова опираются.

Everything in this module is the Russian wire protocol with the models: control
tags the GM writes, words the players say, character names. It is parsed out of
Russian free text. Do not translate it — the prompts are Russian and translating
these strings changes what is being measured, not just what it is called.

Игровые таблицы правил (сложности в dice.py, локации и формулы ран в combat.py)
сюда не вынесены: они не разговорные, живут рядом с кодом, который их считает,
и помечены там же.
"""

from __future__ import annotations

# Мастер за столом. Имя одно на весь проект: раньше литерал «Мастер» лежал
# отдельно в session.py, restore.py и run.py.
