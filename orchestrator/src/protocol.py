# Ресурсы. Игрок пишет «ТРАЧУ УДАЧУ» в любом падеже, поэтому ловим по основе
# слова. Ключ — основа в тексте игрока, значение — имя ресурса.
STEM_FATE = "судьб"
FATE = "судьба"
RESOURCE_STEMS = {
    "удач": "удача",
    "решимост": "решимость",
    "стойкост": "стойкость",
    STEM_FATE: FATE,
}


def alternation(основы) -> str:
    """Альтернатива для регулярки: основа + любой хвост падежа."""
    return "|".join(rf"{основа}\w*" for основа in основы)
