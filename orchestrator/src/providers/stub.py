"""Заглушки вместо моделей: сухой прогон без единого токена.

Сценарий подобран так, чтобы задеть все ветки маршрутизации: смена режима,
пропущенный тег, проверка с остановкой мастера, тайный ход, блок «ТОЛЬКО ДЛЯ»,
самоброски у мастера и у игрока, финал.
"""

from __future__ import annotations

import json
import re

from .base import Ответ, зарегистрировать


class СессияЗаглушка:
    def __init__(self, агент: str, роль: str, модель: str):
        self.агент = агент
        self.роль = роль
        self.модель = модель
        self.вызовов = 0
        self.сцен = 0

    async def отправить(self, текст: str) -> Ответ:
        self.вызовов += 1
        if self.роль == "судья":
            ответ = self._судья(текст)
        elif self.роль == "мастер":
            ответ = self._мастер(текст)
        else:
            ответ = self._игрок(текст)
        return Ответ(
            текст=ответ, провайдер="stub", модель=self.модель,
            латентность_мс=0, токены={"вход": len(текст), "выход": len(ответ)},
            стоимость=0.0,
        )

    async def закрыть(self) -> None:
        return None

    # --- мастер -----------------------------------------------------------
    # Расписание режимов по сценам: первые шесть разговорных, чтобы сухой прогон
    # задел ротацию стартового игрока, дальше действие.
    РАСПИСАНИЕ = ["РАЗГОВОР"] * 6 + ["ДЕЙСТВИЕ"] * 9

    def _мастер(self, входящее: str) -> str:
        продолжение = any(с in входящее for с in
                          ("Результаты бросков", "Результаты атак", "недействителен"))
        if not продолжение:
            self.сцен += 1
        сцена = self.сцен
        режим = self.РАСПИСАНИЕ[min(сцена, len(self.РАСПИСАНИЕ)) - 1]
        тег = f"\n\n[РЕЖИМ: {режим}]"

        if продолжение:
            if "Результаты атак" in входящее:
                return "Тварь отшатывается в темноту, но не уходит." + тег
            return (
                "Грязь на подоконнике чёрная и жирная, пахнет стоячей водой. "
                "Ханна вытирает пальцы о штаны и молчит." + тег
            )

        if сцена == 1:
            return (
                "Утро пришло тихое, дождь кончился, и дом стоит как нежилой. "
                "Отто Гримм лежит на полу своей комнаты, дверь была заперта изнутри. "
                "Сундук на месте, печать цела, внутри свинец в тряпье. "
                "К полудню на мост придёт патруль." + тег
            )
        if сцена == 2:  # проверка: мастер обязан остановиться и ждать бросок
            return "ПРОВЕРКА: Ханна, Восприятие, испытание"
        if сцена == 3:
            return "Гретель ставит кружку на стол и смотрит мимо." + тег
        if сцена == 4:  # личный блок
            return (
                "Йорг качается на лавке и считает пальцы.\n\n"
                "ТОЛЬКО ДЛЯ Лизель\n"
                "Ты замечаешь, что сержант на мосту сверяет бумаги по списку." + тег
            )
        if сцена == 5:  # самоброс мастера
            return (
                "Где-то под полом капает вода. Бросок вышел 77, и Гретель "
                "отводит глаза."
            )
        if сцена == 6:
            return "Лестница в погреб пахнет стоячей водой." + тег
        if сцена == 7:  # тега режима нет вообще — проверка умолчания
            return "Никто не хочет идти первым."
        if сцена == 8:  # две проверки в одной сцене
            return "ПРОВЕРКА: Курт, Сила воли, трудно\nПРОВЕРКА: Лизель, Ловкость, легко"
        if сцена == 9:  # выбытие
            return (
                "Тварь достаёт Ханну когтем поперёк груди, и она оседает в воду "
                "лицом вниз.\n[ВЫБЫЛ: Ханна, без сознания]" + тег
            )
        if сцена == 10:  # третий ДЕЙСТВИЕ подряд — должен сработать сторожок
            return "Вода прибывает, свет фонаря дрожит." + тег
        if сцена == 11:  # возвращение
            return (
                "Ханна кашляет и переворачивается на бок — жива.\n"
                "[ВЕРНУЛСЯ: Ханна]" + тег
            )
        if сцена == 12:  # бой: атака по бронированному и по голому
            return (
                "Тварь выходит из воды.\n"
                "АТАКА: Тварь → Курт, когти\n"
                "АТАКА: Ансельм → Тварь, молот" + тег
            )
        if сцена == 13:  # ответная свалка
            return (
                "Свалка у лаза.\n"
                "АТАКА: Курт → Тварь, меч\n"
                "АТАКА: Тварь → Лизель, когти" + тег
            )
        if сцена == 14:  # добиваем: кто-то дойдёт до нуля и получит крит
            return (
                "Тварь бьёт наотмашь.\n"
                "АТАКА: Тварь → Лизель, когти\n"
                "АТАКА: Тварь → Лизель, когти" + тег
            )
        if сцена == 15:
            return (
                "Ещё удар.\n"
                "АТАКА: Тварь → Лизель, когти\n"
                "АТАКА: Тварь → Ханна, когти" + тег
            )
        return "Патруль уходит по мосту, и дорога остаётся пустой.\n\n[ФИНАЛ]"

    # --- игроки -----------------------------------------------------------
    def _игрок(self, входящее: str) -> str:
        обращение = ""
        чужие = re.findall(r"ХОД ИГРОКА — ([А-ЯЁа-яё]+)", входящее)
        if чужие:
            обращение = f'"{чужие[-1]}, помолчи," — говорит {self.агент}. '

        if self.агент == "Лизель" and self.вызовов == 3:
            return f"ТАЙНО {self.агент} проверяет, на месте ли грамота, и отходит к двери."
        if self.агент == "Курт" and self.вызовов == 4:
            return f"{self.агент} кидает на силу воли, выпало 42, и держится."
        if "Тратишь Судьбу?" in входящее:
            # Заглушка отвечает согласием: проверяем ветку с отменой смерти.
            return "ДА. Лизель цепляется за жизнь и уходит в темноту."
        return (
            f"{обращение}{self.агент} смотрит в кружку и говорит коротко, "
            f"ход номер {self.вызовов}."
        )

    # --- судья ------------------------------------------------------------
    КРИТЕРИИ = ["сеттинг", "правила", "цель", "тайна", "драма"]

    def _судья(self, входящее: str) -> str:
        """Разбирает поданный транскрипт и выдаёт JSON с настоящими цитатами.

        Баллы берутся из хеша, а не из смысла: заглушка проверяет конвейер
        скоринга, а не качество игры.
        """
        реплики: dict[str, list[tuple[int, str]]] = {}
        круг = 0
        for строка in входящее.splitlines():
            шапка = re.match(r"##\s*Круг\s+(\d+)", строка)
            if шапка:
                круг = int(шапка.group(1))
                continue
            реплика = re.match(r"([А-ЯЁ]+)(?:\s*\[[^\]]*\])?:\s*(.+)", строка)
            if реплика and реплика.group(1) != "МАСТЕР":
                имя = реплика.group(1).capitalize()
                реплики.setdefault(имя, []).append((круг, реплика.group(2).strip()))

        персонажи = {}
        # Номер прохода задаёт разброс: без него медиана и разброс не проверяются.
        номер = int((re.search(r"(\d+)$", self.агент) or re.match("1", "1")).group(1))
        сдвиг = (номер - 1) % 3 - 1
        for имя, найденные in реплики.items():
            критерии = {}
            for н, критерий in enumerate(self.КРИТЕРИИ):
                круг_ц, цитата = найденные[min(н, len(найденные) - 1)]
                балл = 1 + (sum(map(ord, имя)) + н) % 5
                балл = max(1, min(5, балл + (сдвиг if н == 0 else 0)))
                критерии[критерий] = {
                    "балл": балл, "круг": круг_ц,
                    "цитата": " ".join(цитата.split()[:8]),
                    "пояснение": "заглушка",
                }
            персонажи[имя] = {"критерии": критерии, "штрафы": []}
        return json.dumps({"персонажи": персонажи}, ensure_ascii=False)


class ПровайдерЗаглушка:
    имя = "stub"

    def __init__(self, **_):
        self.сессии: list[СессияЗаглушка] = []

    async def открыть(self, агент: str, системный_промпт: str, модель: str) -> СессияЗаглушка:
        if агент.startswith("Судья"):
            роль = "судья"
        else:
            роль = "мастер" if агент == "Мастер" else "игрок"
        сессия = СессияЗаглушка(агент, роль, модель)
        self.сессии.append(сессия)
        return сессия

    async def завершить(self) -> None:
        for сессия in self.сессии:
            await сессия.закрыть()


зарегистрировать("stub", ПровайдерЗаглушка)
зарегистрировать("заглушка", ПровайдерЗаглушка)
