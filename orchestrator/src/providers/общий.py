"""Общая механика трёх сторонних провайдеров: HTTP, повторы, учёт, отказы.

Различаются они только формой запроса и формой ответа. Всё остальное — история
диалога, единые параметры, экспоненциальная пауза по частотным лимитам, счёт
токенов и денег, ловля отказов — одно и то же, и живёт здесь. Адаптеру остаётся
четыре метода: куда стучаться, с какими заголовками, что послать, как разобрать.

SDK вендоров сюда намеренно не тащим. Их три, они тянут за собой зависимости и
прячут сырой usage, а нам нужен именно он: доля попаданий в кэш и токены
размышления идут в статью и должны быть видны как есть, а не в пересказе обёртки.
"""

from __future__ import annotations

import asyncio
import hashlib
import random
import time
from dataclasses import dataclass, field

import httpx

from . import отказы as модуль_отказов
from .base import Ответ
from .настройки import Параметры

# Коды, после которых имеет смысл подождать и повторить. Всё остальное — наша
# ошибка (не тот ключ, не та модель, не то поле), и повтор её не вылечит.
ПОВТОРЯЕМЫЕ = {408, 409, 425, 429, 500, 502, 503, 504, 529}


def метка_агента(агент: str) -> str:
    """Опознаватель агента для HTTP-заголовков.

    Заголовки обязаны быть ASCII, а персонажей у нас зовут Курт и Ханна. Берём
    устойчивый отпечаток имени: он не меняется между кругами — а именно на это
    опирается липкость кэша, — и не содержит ни одной кириллической буквы.
    """
    отпечаток = hashlib.sha256(агент.encode("utf-8")).hexdigest()[:12]
    return f"nri-{отпечаток}"


@dataclass
class Расход:
    """Счётчик на одного провайдера. Токены размышления входят в выходные.

    Разделять их нельзя: вендоры выставляют счёт за размышление по цене выхода и
    уже включают его в output_tokens. Мы храним размышление отдельной строкой,
    чтобы показать долю, но в деньги оно идёт один раз.
    """

    вход: int = 0
    выход: int = 0
    размышление: int = 0
    кэш_чтение: int = 0
    кэш_запись: int = 0
    запросов: int = 0
    повторов: int = 0
    отказов: int = 0
    обрывов: int = 0            # ответов, упёршихся в предел_ответа
    деньги: float = 0.0
    секунд: float = 0.0

    @property
    def доля_кэша(self) -> float | None:
        """Какая часть входа пришла из кэша. Влияет на цену, скорость и статью."""
        всего = self.вход + self.кэш_чтение
        return round(self.кэш_чтение / всего, 4) if всего else None

    @property
    def доля_размышления(self) -> float | None:
        return round(self.размышление / self.выход, 4) if self.выход else None

    def словарь(self) -> dict:
        итог = {
            "вход": self.вход, "выход": self.выход,
            "из_них_размышление": self.размышление,
            "кэш_чтение": self.кэш_чтение, "кэш_запись": self.кэш_запись,
            "запросов": self.запросов, "повторов": self.повторов,
            "отказов": self.отказов, "обрывов_по_пределу": self.обрывов,
            "деньги_usd": round(self.деньги, 6),
            "секунд": round(self.секунд, 1),
        }
        if self.доля_кэша is not None:
            итог["доля_кэша"] = self.доля_кэша
        if self.доля_размышления is not None:
            итог["доля_размышления"] = self.доля_размышления
        return итог


@dataclass
class Токены:
    """Нормализованный usage. Каждый адаптер приводит вендорский к этому виду."""

    вход: int = 0
    выход: int = 0
    размышление: int = 0
    кэш_чтение: int = 0
    кэш_запись: int = 0
    сырое: dict = field(default_factory=dict)   # как прислал вендор, для сверки

    def словарь(self) -> dict:
        return {
            "вход": self.вход, "выход": self.выход,
            "размышление": self.размышление,
            "кэш_чтение": self.кэш_чтение, "кэш_запись": self.кэш_запись,
            "сырое": self.сырое,
        }


@dataclass
class Разбор:
    """Что адаптер выудил из ответа вендора."""

    текст: str
    токены: Токены
    модель_факт: str | None = None
    сигнал_отказа: str | None = None    # finish_reason/refusal, если вендор сказал прямо
    оборван: bool = False               # упёрлись в предел_ответа
    # Кто реально обслужил запрос. У прямых подключений это сам вендор, у
    # прослойки — апстрим, который она выбрала, и он может смениться.
    апстрим: str | None = None
    # Деньги, посчитанные самим вендором. Если он их отдаёт, они точнее нашего
    # пересчёта по ставкам из конфига, и берём мы именно их.
    деньги: float | None = None


class ОшибкаПровайдера(RuntimeError):
    pass


class СессияHTTP:
    """Один агент. Историю держит адаптер: так она видна и попадает в лог."""

    def __init__(self, провайдер: "ПровайдерHTTP", агент: str,
                 системный_промпт: str, модель: str):
        self.агент = агент
        self.модель = модель
        self.системный_промпт = системный_промпт
        self._провайдер = провайдер
        self.история: list[dict] = []

    async def отправить(self, текст: str) -> Ответ:
        self.история.append({"роль": "user", "текст": текст})
        ответ = await self._провайдер.запросить(self, текст)
        # Отказ в историю кладём как есть: следующий круг должен видеть, что
        # персонаж промолчал, а не получить дыру в диалоге.
        self.история.append({"роль": "assistant", "текст": ответ.текст})
        return ответ

    async def закрыть(self) -> None:
        return None


class ПровайдерHTTP:
    """Основа трёх адаптеров. Наследник задаёт форму запроса и разбор ответа."""

    имя = "?"
    базовый_url = ""

    # С какой доли лимита начинаем тревожиться. Три четверти дают запас в
    # несколько кругов, чтобы успеть поднять потолок до того, как обрежет.
    ПОРОГ_ТРЕВОГИ = 0.75

    def __init__(
        self,
        параметры: Параметры | None = None,
        цены: dict | None = None,
        журнал=None,
        **_,
    ):
        self.параметры = параметры or Параметры()
        self.цены = цены or {}
        self.журнал = журнал
        self.расход = Расход()
        self.сессии: list[СессияHTTP] = []
        self.отказы: list[dict] = []
        # Что вендор отверг и мы перестали слать. Заполняется живым ответом API,
        # а не догадкой: документация про температуру у рассуждающих моделей
        # молчит, а в отчёт нужно писать проверенное.
        self.отброшенные: set[str] = set()
        self.добытые_расхождения: list[str] = []
        self._клиент = httpx.AsyncClient(
            timeout=httpx.Timeout(self.параметры.таймаут_с, connect=30.0),
            # Пять агентов бьют одновременно в режиме ДЕЙСТВИЕ: соединения держим
            # открытыми, иначе на каждый ход уходит лишнее рукопожатие TLS.
            limits=httpx.Limits(max_keepalive_connections=8, max_connections=16),
        )

    # --- то, что задаёт наследник ------------------------------------------

    def _url(self) -> str:
        raise NotImplementedError

    def _заголовки(self, сессия: "СессияHTTP") -> dict[str, str]:
        raise NotImplementedError

    def _тело(self, сессия: СессияHTTP) -> dict:
        raise NotImplementedError

    def _разобрать(self, данные: dict) -> Разбор:
        raise NotImplementedError

    # --- общее --------------------------------------------------------------

    async def открыть(self, агент: str, системный_промпт: str, модель: str) -> СессияHTTP:
        сессия = СессияHTTP(self, агент, системный_промпт, модель)
        self.сессии.append(сессия)
        return сессия

    async def завершить(self) -> None:
        await self._клиент.aclose()

    def что_задано(self, сессия: "СессияHTTP | None" = None) -> dict:
        """Что действительно ушло в запрос, а не что мы собирались послать.

        Читается из готового тела, поэтому снятый на ходу параметр здесь честно
        отсутствует. Отчёт должен показывать отправленное, а не намерения.
        """
        проба = сессия or СессияHTTP(self, "проба", "", "проба")
        тело = self._тело(проба)
        поля = ("temperature", "top_p", "max_tokens", "max_output_tokens",
                "reasoning", "reasoning_effort", "thinking_level")
        задано = {к: з for к, з in тело.items() if к in поля}
        настройки_генерации = тело.get("generation_config")
        if isinstance(настройки_генерации, dict):
            задано.update({к: з for к, з in настройки_генерации.items() if к in поля})
        return задано

    def _записать(self, тип_события: str, **поля) -> None:
        if self.журнал is not None:
            self.журнал(тип_события, провайдер=self.имя, **поля)

    def _посчитать_деньги(self, токены: Токены) -> float | None:
        """Цены — за миллион токенов, из конфига. Своих чисел здесь нет.

        Размышление отдельно не считаем: вендор уже включил его в выходные и
        берёт за него цену выхода. Второй раз платить не за что.
        """
        цены = self.цены.get(self.имя)
        if not цены:
            return None
        за_миллион = lambda ключ: float(цены.get(ключ) or 0.0) / 1_000_000
        return (
            токены.вход * за_миллион("вход")
            + токены.выход * за_миллион("выход")
            + токены.кэш_чтение * за_миллион("кэш_чтение")
            + токены.кэш_запись * за_миллион("кэш_запись")
        )

    async def запросить(self, сессия: СессияHTTP, _текст: str) -> Ответ:
        тело = self._тело(сессия)
        начало = time.monotonic()
        повторов = 0
        последняя: Exception | None = None

        for попытка in range(1, self.параметры.попыток + 1):
            try:
                ответ_http = await self._клиент.post(
                    self._url(), headers=self._заголовки(сессия), json=тело
                )
            except (httpx.TimeoutException, httpx.TransportError) as ошибка:
                последняя = ошибка
                пауза = self._пауза(попытка, None)
                self._записать(
                    "повтор", кто=сессия.агент, попытка=попытка,
                    причина=f"сеть: {type(ошибка).__name__}", ждём_с=round(пауза, 1),
                )
                повторов += 1
                await asyncio.sleep(пауза)
                continue

            if ответ_http.status_code in ПОВТОРЯЕМЫЕ:
                последняя = ОшибкаПровайдера(
                    f"HTTP {ответ_http.status_code}: {ответ_http.text[:300]}"
                )
                пауза = self._пауза(попытка, ответ_http.headers.get("retry-after"))
                self._записать(
                    "повтор", кто=сессия.агент, попытка=попытка,
                    причина=f"HTTP {ответ_http.status_code}"
                            + (" (частотный лимит)" if ответ_http.status_code == 429 else ""),
                    ждём_с=round(пауза, 1),
                )
                повторов += 1
                await asyncio.sleep(пауза)
                continue

            if ответ_http.status_code >= 400:
                # Вендор мог отвергнуть необязательный параметр — например,
                # температуру у рассуждающей модели. Тогда снимаем его, пишем в
                # расхождения и идём дальше без него: прогон важнее параметра,
                # но замолчать потерю нельзя, она уходит в отчёт.
                снятое = self._снять_отвергнутое(ответ_http.text)
                if снятое:
                    тело = self._тело(сессия)
                    self._записать(
                        "параметр_отвергнут", кто=сессия.агент, параметр=снятое,
                        ответ=ответ_http.text[:300],
                    )
                    continue
                # Не тот ключ, не та модель, не то поле. Пауза этого не вылечит,
                # и молчать об этом посреди прогона нельзя.
                raise ОшибкаПровайдера(
                    f"{self.имя}: HTTP {ответ_http.status_code} — "
                    f"{ответ_http.text[:500]}"
                )

            разбор = self._разобрать(ответ_http.json())
            прошло = time.monotonic() - начало
            return self._собрать(сессия, разбор, прошло, повторов)

        raise ОшибкаПровайдера(
            f"{self.имя}: {self.параметры.попыток} попыток подряд без ответа, "
            f"последняя ошибка — {последняя!r}"
        )

    # Параметры, без которых прогон возможен. Модель и лимит ответа сюда не
    # входят: без них сравнивать нечего, и падать надо громко.
    СНИМАЕМЫЕ = ("temperature", "top_p", "reasoning_effort", "thinking_level")

    def _снять_отвергнутое(self, ответ: str) -> str | None:
        """Ищет в тексте ошибки имя параметра, который вендор не принял."""
        низ = ответ.lower()
        if not any(с in низ for с in
                   ("unsupported", "not supported", "unknown", "invalid", "unrecognized")):
            return None
        for параметр in self.СНИМАЕМЫЕ:
            if параметр in низ and параметр not in self.отброшенные:
                self.отброшенные.add(параметр)
                self.добытые_расхождения.append(
                    f"{параметр} эта модель не принимает — параметр снят, "
                    f"идёт вендорское умолчание (выяснено ответом API, не документацией)"
                )
                return параметр
        return None

    def _пауза(self, попытка: int, retry_after: str | None) -> float:
        """Экспоненциально, с потолком и дрожанием.

        Дрожание не украшение: пятеро агентов упираются в лимит одновременно и
        без него синхронно ломятся обратно в ту же секунду.
        """
        if retry_after:
            try:
                return min(float(retry_after), self.параметры.предел_паузы_с)
            except ValueError:
                pass
        основа = self.параметры.пауза_с * (2 ** (попытка - 1))
        return min(основа, self.параметры.предел_паузы_с) * random.uniform(0.8, 1.3)

    def _собрать(self, сессия: СессияHTTP, разбор: Разбор,
                 прошло: float, повторов: int) -> Ответ:
        деньги = (разбор.деньги if разбор.деньги is not None
                  else self._посчитать_деньги(разбор.токены))
        отказ = модуль_отказов.распознать(разбор.текст, разбор.сигнал_отказа)

        self.расход.вход += разбор.токены.вход
        self.расход.выход += разбор.токены.выход
        self.расход.размышление += разбор.токены.размышление
        self.расход.кэш_чтение += разбор.токены.кэш_чтение
        self.расход.кэш_запись += разбор.токены.кэш_запись
        self.расход.запросов += 1
        self.расход.повторов += повторов
        self.расход.секунд += прошло
        if деньги:
            self.расход.деньги += деньги
        if разбор.оборван:
            self.расход.обрывов += 1

        метки: list[str] = []
        if разбор.оборван:
            метки.append("оборван_по_пределу")
            self._записать("аномалия_обрыв", кто=сессия.агент,
                           предел=self.параметры.предел_ответа)
        elif разбор.токены.выход >= self.параметры.предел_ответа * self.ПОРОГ_ТРЕВОГИ:
            # Узнавать об обрыве постфактум поздно: ход уже испорчен, а прогон
            # идёт без присмотра. Размышление растёт вместе с контекстом, так
            # что о подходе к потолку надо знать заранее — за несколько кругов.
            метки.append("близко_к_пределу")
            self._записать(
                "подход_к_пределу", кто=сессия.агент,
                выход=разбор.токены.выход, размышление=разбор.токены.размышление,
                предел=self.параметры.предел_ответа,
                доля=round(разбор.токены.выход / self.параметры.предел_ответа, 3),
            )
        if отказ is not None:
            # Метка по уверенности: только «отказ» глушит ход. Сбой языка и
            # подозрение доставляются за стол как обычная реплика — иначе
            # законный ход на чужом языке пропадает, как случилось у Grok
            # на двадцать четвёртом круге третьего прогона.
            метки.append({"отказ": "отказ",
                          "подозрение": "подозрение_на_отказ"}.get(
                              отказ.уверенность, отказ.уверенность))
            if отказ.уверенный:
                self.расход.отказов += 1
            запись = {"кто": сессия.агент, "модель": сессия.модель, **отказ.словарь()}
            self.отказы.append(запись)
            # Повтора здесь нет и не будет: тихий ретрай спрятал бы ровно то,
            # ради чего всё затевалось.
            self._записать("отказ", **запись)

        return Ответ(
            текст=разбор.текст,
            провайдер=self.имя,
            модель=сессия.модель,
            латентность_мс=int(прошло * 1000),
            токены=разбор.токены.словарь(),
            стоимость=деньги,
            модель_факт=разбор.модель_факт,
            метки=метки,
        )
