"""Раны, урон и травмы. Считает скрипт, модели описывают.

Кубики у моделей уже отняты — модель кидает подозрительно удачно. Раны отняты
по той же причине: модель списывает их подозрительно драматично. Здесь вся
арифметика боя, и ни строчки её нет в промптах.

Цифры оружия, брони и таблица критов — наши, написаны под этот модуль. Из книги
не переносилось ничего.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field, asdict
from pathlib import Path

from .dice import Кубики, нормализовать

ЛОКАЦИИ = (
    (9, "голова"), (24, "левая рука"), (44, "правая рука"),
    (79, "корпус"), (89, "левая нога"), (100, "правая нога"),
)

ФОРМУЛЫ_РАН = {
    "средний": lambda сб, тб, свб: сб + 2 * тб + свб,
    "мелкий": lambda сб, тб, свб: 2 * тб + свб,
    "крошечный": lambda сб, тб, свб: тб,
    "крохотный": lambda сб, тб, свб: 1,
    "большой": lambda сб, тб, свб: (сб + 2 * тб + свб) * 2,
    "огромный": lambda сб, тб, свб: (сб + 2 * тб + свб) * 4,
    "чудовищный": lambda сб, тб, свб: (сб + 2 * тб + свб) * 8,
}


def бонус(значение: int) -> int:
    """Бонус характеристики — её первая цифра."""
    return значение // 10


def локация(бросок: int) -> str:
    """Место попадания: цифры броска атаки переворачиваются. 43 → 34."""
    перевёрнутый = int(f"{бросок % 100:02d}"[::-1]) or 100
    for порог, имя in ЛОКАЦИИ:
        if перевёрнутый <= порог:
            return имя
    return "корпус"


def дубль(бросок: int) -> bool:
    """11, 22, … 99 и 100. Сто — всегда провал, значит всегда фумбл."""
    if бросок == 100:
        return True
    return бросок % 11 == 0 and бросок > 0


@dataclass
class Боец:
    имя: str
    характеристики: dict
    размер: str = "средний"
    раны_макс: int = 0
    раны: int = 0
    броня: dict = field(default_factory=dict)
    оружие: list = field(default_factory=list)
    состояния: list = field(default_factory=list)
    травмы: list = field(default_factory=list)
    криты_по_локациям: dict = field(default_factory=dict)
    штраф: int = 0
    # Четыре ресурса, две пары. В каждой постоянный и восполняемый, и запас
    # восполняемого равен текущему значению постоянного: потратил Судьбу —
    # навсегда упал потолок Удачи. Потолки держим отдельными полями, потому что
    # текущее значение может быть ниже, а вот выше потолка — никогда.
    судьба: int = 0
    удача: int = 0
    удача_макс: int = 0
    стойкость: int = 0
    решимость: int = 0
    решимость_макс: int = 0
    мотивация: str = ""
    # Круги, на которые Решимость сняла все эффекты разом. Пока счётчик не ноль,
    # состояния остаются в списке, но не кусаются: страх, боль, раны — ничего
    # не мешает. Что именно это оправдывает в сцене, решает мастер.
    иммунитет_кругов: int = 0
    без_сознания: bool = False
    мёртв: bool = False
    потерянные_конечности: list = field(default_factory=list)

    @property
    def тб(self) -> int:
        return бонус(self.характеристики.get("Выносливость", 30))

    @property
    def сб(self) -> int:
        return бонус(self.характеристики.get("Сила", 30))

    def словарь(self) -> dict:
        return asdict(self)


@dataclass
class Результат:
    атакующий: str
    цель: str
    оружие: str
    бросок_атаки: int = 0
    цель_атаки: int = 0
    уу_атаки: int = 0
    бросок_защиты: int = 0
    цель_защиты: int = 0
    уу_защиты: int = 0
    разница: int = 0
    попадание: bool = False
    локация: str = ""
    урон_до_брони: int = 0
    защита: int = 0
    ран_снято: int = 0
    ран_осталось: int = 0
    дубль: bool = False
    крит: dict | None = None
    состояния: list = field(default_factory=list)
    травма: str | None = None
    смерть: bool = False
    ждёт_судьбу: bool = False
    метки: list = field(default_factory=list)

    def словарь(self) -> dict:
        return asdict(self)

    def строкой(self) -> str:
        """Сухой результат для мастера: он превращает его в сцену."""
        if not self.попадание:
            причина = "промах" if self.уу_атаки < 0 else "защита выдержала"
            return f"{self.атакующий} бьёт {self.цель} ({self.оружие}) — {причина}."

        куски = [f"{self.атакующий} попал: {self.цель}, {self.локация}"]
        if self.ран_снято:
            куски.append(f"{self.ран_снято} ран, осталось {self.ран_осталось} "
                         f"из {self.раны_макс_цели}")
        else:
            куски.append("броня и выносливость погасили весь урон")
        if self.крит:
            куски.append(f"КРИТИЧЕСКОЕ РАНЕНИЕ: {self.крит['текст']}")
        if self.состояния:
            куски.append("состояния: " + ", ".join(self.состояния))
        if self.травма:
            куски.append(f"травма: {self.травма}")
        if self.смерть:
            куски.append("СМЕРТЬ" + (" — игрок решает про Судьбу" if self.ждёт_судьбу else ""))
        return ". ".join(куски) + "."

    раны_макс_цели: int = 0


class Боевка:
    """Листы всех участников и вся арифметика боя."""

    def __init__(self, конфиг: dict, кубики: Кубики, путь_критов: str | Path):
        self.конфиг = конфиг
        self.кубики = кубики
        таблица = json.loads(Path(путь_критов).read_text(encoding="utf-8"))
        self.криты = таблица["локации"]
        self.лечение = таблица["лечение"]
        self.оружие = {нормализовать(и): д for и, д in конфиг.get("оружие", {}).items()}
        self.состояния_справочник = {
            нормализовать(и): д for и, д in конфиг.get("состояния", {}).items()
        }
        self.бойцы: dict[str, Боец] = {}
        self.счётчики = {
            "атак": 0, "попаданий": 0, "критов": 0, "фумблов": 0,
            "дублей": 0, "смертей": 0, "судьба_потрачена": 0,
        }
        self.ран_потеряно: dict[str, int] = {}
        self.дошли_до_нуля: set[str] = set()

        карточки = {**конфиг.get("персонажи", {}), **конфиг.get("персонажи_мира", {})}
        for имя in карточки:
            self.лист(имя)

    # --- листы ------------------------------------------------------------

    def лист(self, имя: str) -> Боец:
        """Лист бойца. Безымянному персонажу мира выдаётся заготовка."""
        if имя in self.бойцы:
            return self.бойцы[имя]

        карточки = {**self.конфиг.get("персонажи", {}),
                    **self.конфиг.get("персонажи_мира", {})}
        карточка = карточки.get(имя)
        if карточка is None:
            база = self.конфиг.get("база_по_умолчанию", 30)
            карточка = {
                "характеристики": {к: база for к in
                                   ("Боевые навыки", "Сила", "Выносливость",
                                    "Сила воли", "Ловкость", "Инициатива")},
                "размер": "средний", "оружие": ["кулаки"], "броня": {},
            }

        характеристики = карточка["характеристики"]
        боец = Боец(
            имя=имя,
            характеристики=характеристики,
            размер=карточка.get("размер", "средний"),
            броня=dict(карточка.get("броня", {})),
            оружие=list(карточка.get("оружие", ["кулаки"])),
            судьба=int(карточка.get("судьба", 0)),
            стойкость=int(карточка.get("стойкость", 0)),
            мотивация=карточка.get("мотивация", ""),
        )
        # Потолки берутся от постоянных ресурсов, а не из карточки: если в
        # карточке написано иначе, это ошибка данных, и лучше её не размножать.
        боец.удача_макс = боец.судьба
        боец.удача = min(int(карточка.get("удача", боец.судьба)), боец.удача_макс)
        боец.решимость_макс = боец.стойкость
        боец.решимость = min(int(карточка.get("решимость", боец.стойкость)),
                             боец.решимость_макс)
        боец.раны_макс = self.раны_по_формуле(характеристики, боец.размер,
                                              карточка.get("таланты", {}))
        боец.раны = боец.раны_макс
        self.бойцы[имя] = боец
        return боец

    def раны_по_формуле(self, характеристики: dict, размер: str, таланты: dict) -> int:
        """Раны считаются, а не задаются: при росте характеристик пересчитаются."""
        сб = бонус(характеристики.get("Сила", 30))
        тб = бонус(характеристики.get("Выносливость", 30))
        свб = бонус(характеристики.get("Сила воли", 30))
        формула = ФОРМУЛЫ_РАН.get(нормализовать(размер), ФОРМУЛЫ_РАН["средний"])
        итог = формула(сб, тб, свб)
        итог += тб * int(таланты.get("выносливый", 0))
        return max(итог, 1)

    # --- проверки ---------------------------------------------------------

    def _штраф_состояний(self, боец: Боец) -> int:
        # Решимость снимает всё разом на круг: и штрафы от состояний, и общий
        # штраф от критов. Персонаж стиснул зубы — сегодня его ничто не держит.
        if боец.иммунитет_кругов > 0:
            return 0
        штраф = боец.штраф
        for состояние in боец.состояния:
            справка = self.состояния_справочник.get(нормализовать(состояние), {})
            штраф += int(справка.get("штраф", 0))
        return штраф

    def _бросок(self, боец: Боец, навык: str) -> tuple[int, int, int]:
        """Бросок против характеристики со штрафами. Возвращает цель, бросок, УУ."""
        значение = боец.характеристики.get(навык)
        if значение is None:
            значение = боец.характеристики.get("Боевые навыки", 30)
        цель = max(значение + self._штраф_состояний(боец), 1)
        бросок = self.кубики.подставной()
        уу = (цель // 10) - (бросок // 10)
        if бросок <= 5:
            уу = max(уу, 0)
        elif бросок >= 96:
            уу = min(уу, -1)
        return цель, бросок, уу

    # --- атака ------------------------------------------------------------

    def атака(self, кто: str, по_кому: str, чем: str,
              защита: str | None = None) -> Результат:
        атакующий, цель = self.лист(кто), self.лист(по_кому)
        оружие = self.оружие.get(нормализовать(чем), {"тип": "ближний", "рейтинг": 2,
                                                      "качества": []})
        итог = Результат(атакующий=кто, цель=по_кому, оружие=чем)
        итог.раны_макс_цели = цель.раны_макс
        self.счётчики["атак"] += 1

        навык_атаки = ("Стрелковые навыки"
                       if оружие["тип"] in ("механический", "лук")
                       and "Стрелковые навыки" in атакующий.характеристики
                       else "Боевые навыки")
        итог.цель_атаки, итог.бросок_атаки, итог.уу_атаки = self._бросок(
            атакующий, навык_атаки
        )
        навык_защиты = "Ловкость" if нормализовать(защита or "") == "уклонение" \
            else "Боевые навыки"
        итог.цель_защиты, итог.бросок_защиты, итог.уу_защиты = self._бросок(
            цель, навык_защиты
        )
        итог.разница = итог.уу_атаки - итог.уу_защиты

        итог.дубль = дубль(итог.бросок_атаки)
        успех_атаки = итог.бросок_атаки <= итог.цель_атаки and итог.бросок_атаки < 96
        if итог.бросок_атаки <= 5:
            успех_атаки = True
        итог.попадание = успех_атаки and итог.разница > 0

        if итог.дубль:
            self.счётчики["дублей"] += 1
            if not успех_атаки:
                итог.метки.append("фумбл")
                self.счётчики["фумблов"] += 1
            elif итог.попадание:
                итог.метки.append("дубль_крит")
            else:
                # Бросок удался, но защита оказалась лучше: атака не прошла,
                # значит и критического ранения нет — калечить некого.
                итог.метки.append("дубль_без_последствий")

        if not итог.попадание:
            return итог
        self.счётчики["попаданий"] += 1

        # Урон: у луков и арбалетов рейтинг фиксированный, без бонуса Силы.
        прибавка = итог.разница
        единицы, десятки = итог.бросок_атаки % 10, итог.бросок_атаки // 10
        качества = [нормализовать(к) for к in оружие.get("качества", [])]
        if "ранящее" in качества:
            прибавка = max(прибавка, единицы)
        if "пробивающий" in качества:
            прибавка = max(прибавка, десятки)

        база = оружие["рейтинг"] + (0 if оружие["тип"] in ("механический", "лук")
                                    else атакующий.сб)
        итог.урон_до_брони = база + прибавка
        итог.локация = локация(итог.бросок_атаки)
        броня = int(цель.броня.get(итог.локация, 0))
        итог.защита = цель.тб + броня
        итог.ран_снято = max(итог.урон_до_брони - итог.защита, 0)

        if "рубящий" in качества and броня > 0:
            цель.броня[итог.локация] = броня - 1
            итог.метки.append("броня_повреждена")

        # Ноль ран — не смерть. Но любой урон сверх нуля идёт в криты.
        было = цель.раны
        цель.раны = max(цель.раны - итог.ран_снято, 0)
        итог.ран_осталось = цель.раны
        self.ран_потеряно[по_кому] = self.ран_потеряно.get(по_кому, 0) + (было - цель.раны)
        if цель.раны == 0 and было > 0:
            self.дошли_до_нуля.add(по_кому)

        нужен_крит = итог.дубль and итог.попадание
        if было == 0 and итог.ран_снято > 0:
            нужен_крит = True
        if нужен_крит:
            self._критическое(итог, цель)
            if "колющий" in качества:
                # Пробивает насквозь: добавляет урон единицами броска атаки.
                добавка = единицы
                цель.раны = max(цель.раны - добавка, 0)
                итог.ран_снято += добавка
                итог.ран_осталось = цель.раны
                итог.метки.append("колющий_насквозь")
                self.ран_потеряно[по_кому] = self.ран_потеряно.get(по_кому, 0) + добавка
        return итог

    # --- критические ранения ----------------------------------------------

    def _критическое(self, итог: Результат, цель: Боец) -> None:
        бросок = self.кубики.подставной()
        таблица = self.криты.get(итог.локация, self.криты["корпус"])
        запись = next((з for з in таблица if бросок <= з["порог"]), таблица[-1])

        self.счётчики["критов"] += 1
        итог.крит = {"бросок": бросок, "текст": запись["текст"],
                     "локация": итог.локация}
        цель.криты_по_локациям[итог.локация] = (
            цель.криты_по_локациям.get(итог.локация, 0) + 1
        )

        for состояние in запись.get("состояния", []):
            if состояние not in цель.состояния:
                цель.состояния.append(состояние)
                итог.состояния.append(состояние)
        if запись.get("травма"):
            цель.травмы.append({"тип": запись["травма"], "локация": итог.локация,
                                "текст": запись["текст"], "вылечена": False})
            итог.травма = запись["травма"]
        цель.штраф += int(запись.get("штраф", 0))
        if запись.get("без_сознания"):
            цель.без_сознания = True
            итог.метки.append("без_сознания")
        if запись.get("потеря_конечности"):
            цель.потерянные_конечности.append(итог.локация)
            итог.метки.append("потеря_конечности")

        смерть = bool(запись.get("смерть"))
        # Счётчик критов по локации: перебор над бонусом Выносливости калечит.
        if цель.криты_по_локациям[итог.локация] > цель.тб:
            if итог.локация in ("голова", "корпус"):
                смерть = True
            elif итог.локация not in цель.потерянные_конечности:
                цель.потерянные_конечности.append(итог.локация)
                цель.травмы.append({"тип": "ампутация", "локация": итог.локация,
                                    "текст": f"{итог.локация} потеряна", "вылечена": False})
                итог.травма = "ампутация"
                итог.метки.append("потеря_конечности_по_счётчику")

        if смерть:
            итог.смерть = True
            # Судьбу тратит только игрок и только своим словом.
            итог.ждёт_судьбу = цель.судьба > 0

    def применить_судьбу(self, имя: str, тратит: bool) -> str:
        """Игрок сказал своё слово. Скрипт за него не решает."""
        боец = self.лист(имя)
        if тратит and боец.судьба > 0:
            боец.судьба -= 1
            # Потолок Удачи падает вместе с Судьбой — навсегда. Если текущая
            # Удача была под потолок, она тоже съезжает: держать больше, чем
            # можно накопить, нельзя.
            боец.удача_макс = боец.судьба
            боец.удача = min(боец.удача, боец.удача_макс)
            боец.без_сознания = True
            self.счётчики["судьба_потрачена"] += 1
            return (f"{имя} тратит Судьбу: смерть заменена на беспамятство, "
                    f"осталось Судьбы {боец.судьба}, потолок Удачи теперь "
                    f"{боец.удача_макс}")
        боец.мёртв = True
        self.счётчики["смертей"] += 1
        return f"{имя} умирает"

    # --- четыре ресурса ----------------------------------------------------

    def ресурсы(self, имя: str) -> dict:
        б = self.лист(имя)
        return {
            "судьба": б.судьба, "удача": б.удача, "удача_макс": б.удача_макс,
            "стойкость": б.стойкость, "решимость": б.решимость,
            "решимость_макс": б.решимость_макс,
        }

    def потратить(self, имя: str, ресурс: str) -> dict:
        """Списывает восполняемый ресурс. Не хватило — не списывает и говорит.

        Ход при этом не отклоняется: игрок мог просто ошибиться в счёте, и
        ронять из-за этого круг незачем. Но и эффекта не будет, а попытка
        уйдёт в лог и в сводку мастеру — иначе «трачу Удачу» без Удачи
        засчитается судьёй как настоящая трата, что уже однажды и вышло.
        """
        боец = self.лист(имя)
        было = self.ресурсы(имя)
        поле = {"удача": "удача", "решимость": "решимость"}.get(ресурс)
        if поле is None:
            return {"успех": False, "причина": f"неизвестный ресурс {ресурс!r}",
                    "было": было, "стало": было}

        остаток = getattr(боец, поле)
        if остаток <= 0:
            return {"успех": False, "причина": f"{ресурс} кончилась",
                    "было": было, "стало": было}

        setattr(боец, поле, остаток - 1)
        self.счётчики[f"{ресурс}_потрачена"] = \
            self.счётчики.get(f"{ресурс}_потрачена", 0) + 1
        return {"успех": True, "причина": "", "было": было,
                "стало": self.ресурсы(имя)}

    def потратить_стойкость(self, имя: str) -> dict:
        """Постоянный ресурс: тратится навсегда и роняет потолок Решимости."""
        боец = self.лист(имя)
        было = self.ресурсы(имя)
        if боец.стойкость <= 0:
            return {"успех": False, "причина": "Стойкость кончилась",
                    "было": было, "стало": было}
        боец.стойкость -= 1
        боец.решимость_макс = боец.стойкость
        боец.решимость = min(боец.решимость, боец.решимость_макс)
        self.счётчики["стойкость_потрачена"] = \
            self.счётчики.get("стойкость_потрачена", 0) + 1
        return {"успех": True, "причина": "", "было": было,
                "стало": self.ресурсы(имя)}

    def начислить_решимость(self, имя: str, сколько: int = 1) -> dict:
        """Начисляет мастер за игру по Мотивации. Выше потолка не поднимает."""
        боец = self.лист(имя)
        было = self.ресурсы(имя)
        новое = min(боец.решимость + сколько, боец.решимость_макс)
        добавлено = новое - боец.решимость
        боец.решимость = новое
        self.счётчики["решимость_начислена"] = \
            self.счётчики.get("решимость_начислена", 0) + добавлено
        return {"успех": добавлено > 0, "добавлено": добавлено,
                "причина": "" if добавлено else "Решимость уже под потолок",
                "было": было, "стало": self.ресурсы(имя)}

    # --- состояния и кровотечение -----------------------------------------

    def дать_иммунитет(self, имя: str, кругов: int = 1) -> list[str]:
        """Решимость: на круг персонажа не держит ничто.

        Состояния из списка не убираем — они остались, просто перестали
        мешать. Так честнее для сцены: сломанная рука никуда не делась,
        её обладатель просто перестал её замечать.
        """
        боец = self.лист(имя)
        боец.иммунитет_кругов = max(боец.иммунитет_кругов, кругов)
        return list(боец.состояния)

    def новый_круг(self) -> None:
        """Гасит иммунитеты. Зовётся в начале круга, до любых бросков."""
        for боец in self.бойцы.values():
            if боец.иммунитет_кругов > 0:
                боец.иммунитет_кругов -= 1

    def снять_состояния(self, имя: str, какие: tuple[str, ...]) -> list[str]:
        """Снимает названные состояния. Штраф пересчитывать не надо.

        Он и так считается на лету в _штраф_состояний по текущему списку:
        убрали состояние — штраф ушёл вместе с ним.
        """
        боец = self.лист(имя)
        цели = {нормализовать(с) for с in какие}
        снято = [с for с in боец.состояния if нормализовать(с) in цели]
        боец.состояния = [с for с in боец.состояния if нормализовать(с) not in цели]
        return снято

    def кровоточащие(self) -> list[str]:
        """Кто истекает кровью на нуле ран — этих проверяем каждый раунд."""
        return [имя for имя, б in self.бойцы.items()
                if б.раны == 0 and not б.мёртв
                and any(нормализовать(с) == "кровотечение" for с in б.состояния)]

    def проверка_кровотечения(self, имя: str) -> dict:
        боец = self.лист(имя)
        цель, бросок, уу = self._бросок(боец, "Выносливость")
        успех = бросок <= цель
        итог = {"персонаж": имя, "цель": цель, "выпало": бросок, "успех": успех}
        if not успех:
            боец.без_сознания = True
            итог["последствие"] = "потерял сознание, без помощи умрёт"
        else:
            итог["последствие"] = "держится"
        return итог

    def восстановить(self, имя: str, сколько: int = 1) -> tuple[int, str]:
        """Естественное восстановление ран. Невылеченный крит его запрещает."""
        боец = self.лист(имя)
        незалеченные = [т for т in боец.травмы if not т["вылечена"]]
        if незалеченные:
            типы = ", ".join(т["тип"] for т in незалеченные)
            return 0, f"{имя} не восстанавливается: невылеченное — {типы}"
        было = боец.раны
        боец.раны = min(боец.раны + сколько, боец.раны_макс)
        return боец.раны - было, f"{имя}: раны {боец.раны} из {боец.раны_макс}"

    def лечить(self, имя: str, тип: str, успех: bool) -> str:
        """Лечение по проверке Лечения. Тяжёлое требует хирургии и времени."""
        боец = self.лист(имя)
        травма = next((т for т in боец.травмы
                       if нормализовать(т["тип"]) == нормализовать(тип)
                       and not т["вылечена"]), None)
        if травма is None:
            return f"у {имя} нет невылеченной травмы «{тип}»"
        справка = self.лечение.get(нормализовать(тип), {})
        if справка.get("необратимо"):
            return f"{тип} необратима, лечить нечего"
        if not успех:
            return f"{имя}: лечение не помогло, {тип} остаётся"
        травма["вылечена"] = True
        хвост = " (нужна хирургия и покой)" if справка.get("хирургия") else ""
        return f"{имя}: {тип} вылечена{хвост}, дней покоя {справка.get('дней', 0)}"

    def снять_состояние(self, имя: str, состояние: str) -> bool:
        боец = self.лист(имя)
        было = len(боец.состояния)
        боец.состояния = [с for с in боец.состояния
                          if нормализовать(с) != нормализовать(состояние)]
        return len(боец.состояния) != было

    # --- сводки -----------------------------------------------------------

    def сводка_ресурсов(self, имена: list[str]) -> str:
        """Мастеру — остатки всех четверых каждый круг.

        Ему это нужно не для счёта, а чтобы видеть, кому пора начислить
        Решимость и у кого уже нечего тратить.
        """
        известные = [и for и in имена if и in self.бойцы]
        if not известные:
            return ""
        строки = ["РЕСУРСЫ ИГРОКОВ (считает скрипт, ты только начисляешь Решимость):"]
        for имя in известные:
            строки.append(f"- {имя}: {self.строка_состояния(имя)}")
        return "\n".join(строки)

    def сводка_мастеру(self, участники: list[str] | None = None) -> str:
        """Раны, состояния и травмы всех, кто в сцене. Мастеру — каждый круг."""
        имена = участники or [и for и, б in self.бойцы.items()
                              if б.раны < б.раны_макс or б.состояния or б.травмы]
        if not имена:
            return ""
        строки = ["СОСТОЯНИЕ УЧАСТНИКОВ (считает скрипт, ты только описываешь):"]
        for имя in имена:
            б = self.лист(имя)
            куски = [f"{имя}: раны {б.раны} из {б.раны_макс}"]
            if б.состояния:
                куски.append("состояния: " + ", ".join(б.состояния))
            if б.травмы:
                куски.append("травмы: " + ", ".join(
                    т["тип"] + (" (вылечена)" if т["вылечена"] else "")
                    for т in б.травмы))
            if б.штраф:
                куски.append(f"общий штраф {б.штраф}")
            if б.без_сознания:
                куски.append("без сознания")
            if б.мёртв:
                куски.append("мёртв")
            строки.append("- " + "; ".join(куски))
        return "\n".join(строки)

    def строка_состояния(self, имя: str) -> str:
        """Короткая строка остатка — перед каждым ходом, без исключений.

        Ресурс, упомянутый один раз в карточке на нулевом круге, к двадцатому
        не существует: модель про него не помнит. Это свойство подачи, а не
        модели, и лечится не уговорами в промпте, а вот этой строкой. Поэтому
        она приходит всегда, даже когда всё цело и сказать вроде бы нечего.
        """
        б = self.лист(имя)
        состояния = ", ".join(б.состояния) if б.состояния else "нет"
        куски = [
            f"Раны {б.раны} из {б.раны_макс}",
            f"Судьба {б.судьба}, Удача {б.удача} из {б.удача_макс}",
            f"Стойкость {б.стойкость}, Решимость {б.решимость} из {б.решимость_макс}",
            f"Состояний {состояния}" if состояния == "нет" else f"Состояния: {состояния}",
        ]
        живые_травмы = [т["тип"] for т in б.травмы if not т["вылечена"]]
        if живые_травмы:
            куски.append("травмы: " + ", ".join(живые_травмы))
        return ". ".join(куски) + "."

    def сводка_игроку(self, имя: str) -> str:
        """Свои цифры — каждый круг. Про чужие игрок узнаёт только со стороны."""
        строка = self.строка_состояния(имя)
        if self.лист(имя).раны == 0:
            строка += " Ты на пределе: следующий удар пойдёт по критическим ранениям."
        return "ТВОЁ СОСТОЯНИЕ: " + строка

    def итоги(self) -> dict:
        return {
            **self.счётчики,
            "ран_потеряно": dict(self.ран_потеряно),
            "дошли_до_нуля": sorted(self.дошли_до_нуля),
            "травмы": {имя: [т["тип"] for т in б.травмы]
                       for имя, б in self.бойцы.items() if б.травмы},
            "состояния_на_конец": {имя: б.состояния
                                   for имя, б in self.бойцы.items() if б.состояния},
        }
