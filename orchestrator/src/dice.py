"""Кубики. Кидает только скрипт — ни мастер, ни игроки не кидают никогда.

Генератор с фиксированным зерном: зерно и порядковый номер броска пишутся в лог,
поэтому прогон воспроизводится строка в строку.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass, asdict, replace

# Таблица сложности WFRP 4e. Ключи нормализованы: нижний регистр, «ё» → «е».
СЛОЖНОСТИ: dict[str, int] = {
    "очень легко": 60, "очень легкая": 60, "очень легкое": 60, "очень легкий": 60,
    "легко": 40, "легкая": 40, "легкое": 40, "легкий": 40,
    "средне": 20, "средняя": 20, "среднее": 20, "средний": 20,
    "испытание": 0, "испытующая": 0, "обычная": 0, "обычно": 0, "без модификатора": 0,
    "трудно": -10, "трудная": -10, "трудное": -10, "трудный": -10,
    "тяжело": -20, "тяжелая": -20, "тяжелое": -20, "тяжелый": -20,
    "очень тяжело": -30, "очень тяжелая": -30, "очень тяжелое": -30, "очень тяжелый": -30,
}


def нормализовать(s: str) -> str:
    """Приводит название навыка или сложности к ключу словаря."""
    s = s.strip().lower().replace("ё", "е")
    s = re.sub(r"[«»\"'(),.;:!?\[\]]", " ", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()


def модификатор_сложности(сложность: str) -> tuple[int, bool]:
    """Возвращает модификатор и признак того, что сложность распознана."""
    ключ = нормализовать(сложность)
    if ключ in СЛОЖНОСТИ:
        return СЛОЖНОСТИ[ключ], True
    # «трудная проверка», «тяжёлая (−20)» и прочие хвосты
    for имя, мод in sorted(СЛОЖНОСТИ.items(), key=lambda p: -len(p[0])):
        if ключ.startswith(имя):
            return мод, True
    явный = re.search(r"([+\-−]\s*\d{1,2})", ключ)
    if явный:
        return int(явный.group(1).replace("−", "-").replace(" ", "")), True
    return 0, False


@dataclass
class Бросок:
    персонаж: str
    навык: str
    характеристика: str
    сложность: str
    база: int
    надбавка: int
    модификатор: int
    цель: int
    выпало: int
    успех: bool
    уровни_успеха: int
    авто: str | None
    номер: int
    зерно: int
    метки: list[str]
    дубль: bool = False

    def как_словарь(self) -> dict:
        return asdict(self)

    def кратко(self) -> str:
        итог = "успех" if self.успех else "провал"
        авто = f", {self.авто}" if self.авто else ""
        дубль = ""
        if self.дубль:
            дубль = (", ДУБЛЬ — выдающийся успех, опиши дополнительный эффект"
                     if self.успех else ", ДУБЛЬ — фумбл, опиши осложнение")
        return (
            f"выпало {self.выпало}, цель {self.цель}, {итог}, "
            f"уровней успеха {self.уровни_успеха:+d}{авто}{дубль}"
        )

    def строкой(self) -> str:
        return f"{self.персонаж}, {self.навык}, {self.сложность} — {self.кратко()}"


class Кубики:
    """Сотня с фиксируемым зерном плюс разбор целевого числа по карточке персонажа."""

    ДУБЛИ = (11, 22, 33, 44, 55, 66, 77, 88, 99, 100)

    def __init__(self, конфиг: dict, зерно: int, доля_дублей: float = 0.0):
        self.зерно = зерно
        self._rng = random.Random(зерно)
        self._номер = 0
        # Подкрутка — только для проверочных прогонов: она ломает честность
        # бросков, ради которой всё и затевалось. Каждый подкрученный бросок
        # помечается в логе, чтобы такой прогон нельзя было выдать за настоящий.
        self.доля_дублей = max(0.0, min(float(доля_дублей), 1.0))
        self.подкручено = 0
        # Игроки и персонажи мира в одном справочнике: мастер вправе кидать
        # за Гретель и патруль, и это должны быть их числа, а не заглушка.
        self.персонажи = {**конфиг["персонажи"], **конфиг.get("персонажи_мира", {})}
        self.карта_навыков = {
            нормализовать(k): v for k, v in конфиг["навыки_на_характеристики"].items()
        }
        self.надбавка = конфиг.get("надбавка_за_обученный_навык", 10)
        self.база_по_умолчанию = конфиг.get("база_по_умолчанию", 30)

    def _база(
        self, персонаж: str, навык: str, явная: int | None = None
    ) -> tuple[int, str, int, list[str]]:
        """База, название характеристики, надбавка за обученность, метки."""
        метки: list[str] = []
        карточка = self.персонажи.get(персонаж)
        if карточка is None:
            if явная is not None:
                # Мастер назвал целевое число NPC сам — это характеристика,
                # а не бросок, и запрет на числа её не касается.
                return явная, "названа мастером", 0, ["база_от_мастера"]
            return self.база_по_умолчанию, "?", 0, ["нпс_без_карточки"]

        характеристики = карточка["характеристики"]
        ключ = нормализовать(навык)

        # Явное значение навыка в карточке старше расчёта: в документе у
        # персонажей мира навыки заданы числом, а не характеристикой с надбавкой.
        for имя, значение in карточка.get("навыки", {}).items():
            if нормализовать(имя) == ключ:
                return значение, f"навык {имя}", 0, метки

        # Проверка прямо по характеристике.
        for имя, значение in характеристики.items():
            if нормализовать(имя) == ключ:
                return значение, имя, 0, метки

        # Проверка по навыку: база — характеристика, на которой навык стоит.
        характеристика = self.карта_навыков.get(ключ)
        if характеристика is None:
            метки.append("неизвестный_навык")
            return self.база_по_умолчанию, "?", 0, метки

        обучен = any(
            нормализовать(n) == ключ for n in карточка.get("обученные_навыки", [])
        )
        надбавка = self.надбавка if обучен else 0
        return характеристики[характеристика], характеристика, надбавка, метки

    def подменить(self, бросок: Бросок, значение: int, метка: str) -> Бросок:
        """Тот же бросок, но с выбранным значением вместо выпавшего.

        Нужно для Судьбы: игрок в безнадёжном положении тратит её и называет
        число сам. Пересчитываем всё, что от него зависит — успех, уровни,
        автоматику, дубль, — иначе в лог уйдёт красивая единица с чужим
        исходом. Исходный бросок при этом никуда не девается: он уже записан,
        и сравнение «выпало бы — взял» пойдёт в разбор.
        """
        значение = max(1, min(100, int(значение)))
        успех = значение <= бросок.цель
        уровни = (бросок.цель // 10) - (значение // 10)
        авто = None
        if значение <= 5:
            авто, успех, уровни = "автоуспех", True, max(уровни, 0)
        elif значение >= 96:
            авто, успех, уровни = "автопровал", False, min(уровни, -1)
        дубль = значение == 100 or (значение % 11 == 0 and значение > 0)

        подменённый = replace(
            бросок, выпало=значение, успех=успех, уровни_успеха=уровни,
            авто=авто, дубль=дубль,
            метки=[м for м in бросок.метки if м != "подкручено"] + [метка],
        )
        return подменённый

    def бросить(
        self, персонаж: str, навык: str, сложность: str, явная_база: int | None = None
    ) -> Бросок:
        база, характеристика, надбавка, метки = self._база(персонаж, навык, явная_база)
        модификатор, распознана = модификатор_сложности(сложность)
        if not распознана:
            метки.append("неизвестная_сложность")

        цель = база + надбавка + модификатор
        self._номер += 1
        выпало, подкручен = self._сотня()
        if подкручен:
            метки.append("подкручено")

        авто = None
        успех = выпало <= цель
        уровни = (цель // 10) - (выпало // 10)

        # Автоматика WFRP: 01–05 успех всегда, 96–100 провал всегда.
        if выпало <= 5:
            авто = "автоуспех"
            успех = True
            уровни = max(уровни, 0)
        elif выпало >= 96:
            авто = "автопровал"
            успех = False
            уровни = min(уровни, -1)

        # Дубль на обычной проверке — тоже событие: выдающийся успех или фумбл.
        есть_дубль = выпало == 100 or (выпало % 11 == 0 and выпало > 0)
        if есть_дубль:
            метки.append("дубль_успех" if успех else "фумбл")

        return Бросок(
            персонаж=персонаж, навык=навык, характеристика=характеристика,
            сложность=сложность, база=база, надбавка=надбавка, модификатор=модификатор,
            цель=цель, выпало=выпало, успех=успех, уровни_успеха=уровни, авто=авто,
            номер=self._номер, зерно=self.зерно, метки=метки, дубль=есть_дубль,
        )

    @property
    def бросков(self) -> int:
        return self._номер

    def _сотня(self) -> tuple[int, bool]:
        """Сотня. При подкрутке с заданной долей выдаёт дубль."""
        if self.доля_дублей and self._rng.random() < self.доля_дублей:
            self.подкручено += 1
            return self._rng.choice(self.ДУБЛИ), True
        return self._rng.randint(1, 100), False

    def подставной(self) -> int:
        """Настоящий бросок взамен числа, которое модель назвала сама."""
        self._номер += 1
        return self._сотня()[0]
