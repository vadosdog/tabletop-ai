#!/usr/bin/env python3
"""Тесты парсера: python3 orchestrator/tests/test_parse.py"""

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src import parse  # noqa: E402

ИМЕНА = ["Курт", "Ансельм", "Ханна", "Лизель"]


def тест_режим():
    assert parse.режим("текст\n\n[РЕЖИМ: РАЗГОВОР]") == ("РАЗГОВОР", True)
    assert parse.режим("текст\n[режим: действие]") == ("ДЕЙСТВИЕ", True)
    # Тега нет — умолчание РАЗГОВОР и признак пропуска: молчание мастера
    # толкуется в пользу диалога, на нём держится вся затея.
    assert parse.режим("просто сцена") == ("РАЗГОВОР", False)
    assert parse.режим("просто сцена", "ДЕЙСТВИЕ") == ("ДЕЙСТВИЕ", False)
    # Берётся последний тег, если мастер поставил два.
    assert parse.режим("[РЕЖИМ: ДЕЙСТВИЕ] ... [РЕЖИМ: РАЗГОВОР]")[0] == "РАЗГОВОР"


def тест_служебные_теги_вырезаются():
    чистый = parse.без_служебных_тегов("Сцена.\n\n[РЕЖИМ: РАЗГОВОР]\n\n[ФИНАЛ]")
    assert чистый == "Сцена."


def тест_финал():
    assert parse.объявлен_финал("конец\n[ФИНАЛ]")
    assert not parse.объявлен_финал("это ещё не финал")


def тест_проверки():
    текст = (
        "Ханна щурится в темноту.\n"
        "ПРОВЕРКА: Ханна, Восприятие, испытание\n"
        "**ПРОВЕРКА:** Курт, Сила воли, трудно"
    )
    проверки, аномалии = parse.проверки(текст, ИМЕНА)
    assert len(проверки) == 2 and not аномалии
    assert (проверки[0].персонаж, проверки[0].навык) == ("Ханна", "Восприятие")
    assert проверки[1].сложность == "трудно"


def тест_проверка_без_сложности():
    проверки, аномалии = parse.проверки("ПРОВЕРКА: Лизель, Обман", ИМЕНА)
    assert проверки[0].сложность == "испытание"
    assert "сложность_не_указана" in аномалии


def тест_непарсимая_проверка():
    проверки, аномалии = parse.проверки("ПРОВЕРКА: тут всё непонятно", ИМЕНА)
    assert not проверки and "непарсимая_проверка" in аномалии


def тест_имя_с_фамилией_опознаётся():
    проверки, _ = parse.проверки("ПРОВЕРКА: Ханна Фогель, Скрытность, легко", ИМЕНА)
    assert проверки[0].персонаж == "Ханна"


def тест_выбытие_и_возвращение():
    т = "Курт валится навзничь.\n[ВЫБЫЛ: Курт, без сознания]"
    assert parse.выбытия(т, ИМЕНА) == [("Курт", "без сознания")]
    # Причина необязательна, фамилия в имени не мешает.
    assert parse.выбытия("[ВЫБЫЛ: Ханна Фогель]", ИМЕНА) == [("Ханна", "не указана")]
    assert parse.возвращения("[ВЕРНУЛСЯ: Курт]", ИМЕНА) == ["Курт"]
    assert parse.выбытия("никто не выбыл", ИМЕНА) == []


def тест_теги_выбытия_остаются_в_тексте():
    # Для игроков это событие сцены, а не служебная разметка.
    текст = "Курта уводят.\n[ВЫБЫЛ: Курт, арест]\n\n[РЕЖИМ: РАЗГОВОР]"
    чистый = parse.без_служебных_тегов(текст)
    assert "[ВЫБЫЛ: Курт, арест]" in чистый and "[РЕЖИМ" not in чистый


def тест_строки_атак_не_уходят_игрокам():
    # Иначе все увидят точный остаток ран друг друга, а это запрещено.
    текст = ("Курт бьёт с разворота.\n"
             "АТАКА: Курт → Тварь, меч → попал, 4 ран, осталось 11 из 15.\n"
             "Тварь отшатывается.")
    чистый = parse.без_строк_атак(текст)
    assert "АТАКА" not in чистый and "осталось 11" not in чистый
    assert "Курт бьёт с разворота." in чистый and "Тварь отшатывается." in чистый


def тест_проверка_за_нпс():
    # У персонажа мира нет карточки игрока — это не ошибка разбора.
    проверки, аномалии = parse.проверки("ПРОВЕРКА: Гретель, Обман, испытание", ИМЕНА)
    assert проверки[0].персонаж == "Гретель" and проверки[0].база is None
    assert аномалии == ["проверка_за_нпс"]


def тест_нпс_с_явным_числом():
    проверки, _ = parse.проверки("ПРОВЕРКА: Хозяин мельницы (45), Обман, средне", ИМЕНА)
    assert проверки[0].персонаж == "Хозяин мельницы" and проверки[0].база == 45


def тест_личные_блоки():
    текст = (
        "Общая сцена, её видят все.\n\n"
        "ТОЛЬКО ДЛЯ Лизель\n"
        "Сержант сверяет бумаги по списку.\n\n"
        "ТОЛЬКО ДЛЯ Ханна\n"
        "Пёс скулит и пятится от лаза."
    )
    публично, личное = parse.разделить_личное(текст)
    assert публично == "Общая сцена, её видят все."
    assert set(личное) == {"Лизель", "Ханна"}
    assert "бумаги" in личное["Лизель"] and "Пёс" in личное["Ханна"]


def тест_без_личных_блоков():
    публично, личное = parse.разделить_личное("Обычная сцена.")
    assert публично == "Обычная сцена." and личное == {}


def тест_тайный_ход():
    assert parse.тайный_ход("ТАЙНО Лизель проверяет грамоту.")
    assert parse.тайный_ход("  тайно: она отходит к двери")
    assert not parse.тайный_ход("Лизель тайно проверяет грамоту.")


def тест_самоброски():
    assert parse.самоброски("Курт кидает и выпало 42.")
    assert parse.самоброски("Бросок вышел 77, она отводит глаза.")
    assert parse.самоброски("Результат: 13, успех.")
    assert parse.самоброски("уровни успеха 3")
    # Проза без чисел броска — чисто.
    assert not parse.самоброски("Шесть человек на мосту, сержант нетерпелив.")
    assert not parse.самоброски("Курт кидает мешок на телегу и садится рядом.")


def тест_самоброс_не_считает_выданные_числа():
    # Мастер вправе пересказать результат, который выдал скрипт.
    assert not parse.самоброски("Выпало 37, грязь под ногтями", известные={37})
    assert parse.самоброски("Выпало 38, грязь под ногтями", известные={37})


def тест_подпись_проверок():
    текст = "ПРОВЕРКА: Ханна, Восприятие, испытание\nОна щурится."
    подписано = parse.подписать_проверки(
        текст, {"ПРОВЕРКА: Ханна, Восприятие, испытание": "выпало 12, цель 52, успех"}
    )
    assert "→ выпало 12, цель 52, успех" in подписано
    assert "Она щурится." in подписано


if __name__ == "__main__":
    провалено = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("тест_"):
            try:
                функция()
                print(f"  ok   {имя}")
            except AssertionError as ошибка:
                провалено += 1
                print(f"  ПРОВАЛ {имя}: {ошибка}")
    print("все тесты парсера прошли" if not провалено else f"провалено: {провалено}")
    sys.exit(1 if провалено else 0)
