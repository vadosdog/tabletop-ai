#!/usr/bin/env python3
"""Прослойка: фиксация апстрима и ловля его смены.

    python3 orchestrator/tests/test_openrouter.py

Главное требование к этому адаптеру — чтобы маршрутизатор не сменил хост
посреди прогона незаметно. Проверяется без сети: тело запроса собирается и
разбирается на подсунутых ответах.
"""

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src.providers.настройки import Параметры  # noqa: E402
from src.providers.openrouter import ПровайдерOpenRouter, список_апстримов  # noqa: E402


def сделать(журнал=None, **ещё):
    return ПровайдерOpenRouter(
        параметры=Параметры(), цены={}, журнал=журнал,
        апстримы=["alibaba"], **ещё,
    )


class ПодложнаяСессия:
    агент = "Ханна"
    модель = "qwen/qwen3.7-max"
    системный_промпт = "Ты играешь Ханну Фогель."
    история = [{"роль": "user", "текст": "Твой ход."}]


def ответ(апстрим="Alibaba", **ещё) -> dict:
    основа = {
        "model": "qwen/qwen3.7-max",
        "provider": апстрим,
        "choices": [{"message": {"content": "Ханна молчит и смотрит в пол."},
                     "finish_reason": "stop"}],
        "usage": {"prompt_tokens": 1000, "completion_tokens": 40,
                  "prompt_tokens_details": {"cached_tokens": 800},
                  "completion_tokens_details": {"reasoning_tokens": 12},
                  "cost": 0.00123},
    }
    основа.update(ещё)
    return основа


def тест_апстрим_закреплён_и_фолбэк_запрещён():
    тело = сделать()._тело(ПодложнаяСессия())
    блок = тело["provider"]
    assert блок["order"] == ["alibaba"], блок
    assert блок["allow_fallbacks"] is False, "фолбэк не запрещён — хост может смениться"
    assert блок["require_parameters"] is True, (
        "без require_parameters прослойка вправе отдать запрос апстриму, "
        "который молча выбросит температуру"
    )


def тест_без_списка_апстримов_не_стартуем():
    """Пустой список означал бы «маршрутизируй как хочешь»."""
    for пусто in (None, [], [""]):
        try:
            список_апстримов(пусто)
        except SystemExit:
            continue
        raise AssertionError(f"пустой список {пусто!r} проглочен")


def тест_параметры_генерации_доходят():
    тело = сделать()._тело(ПодложнаяСессия())
    assert тело["temperature"] == 1.0
    # Лимит поднят до 16000: размышление Qwen растёт вместе с контекстом.
    assert тело["max_tokens"] == 16000
    # У прослойки размышление объектом, а не строкой: строковое поле из чат.py
    # должно быть снято, иначе уйдут оба и апстрим ответит ошибкой.
    assert тело["reasoning"] == {"effort": "low"}, тело.get("reasoning")
    assert "reasoning_effort" not in тело
    assert тело["usage"] == {"include": True}, "не просим прослойку посчитать деньги"


def тест_явный_кэш_метит_системный_промпт():
    сообщения = сделать()._тело(ПодложнаяСессия())["messages"]
    системное = сообщения[0]
    assert isinstance(системное["content"], list), "пометка кэша не поставлена"
    assert системное["content"][0]["cache_control"] == {"type": "ephemeral"}
    # Остальные сообщения простые строки: пометка нужна только на неизменном куске.
    assert isinstance(сообщения[1]["content"], str)


def тест_кэш_снимается_если_апстрим_его_не_принял():
    провайдер = сделать()
    снятое = провайдер._снять_отвергнутое(
        '{"error":{"message":"Unsupported field: cache_control"}}'
    )
    assert снятое == "cache_control"
    assert провайдер.явный_кэш is False
    assert any("кэш" in с for с in провайдер.добытые_расхождения)
    # После снятия сообщения снова простые: запрос должен пройти.
    assert isinstance(провайдер._тело(ПодложнаяСессия())["messages"][0]["content"], str)


def тест_кто_ответил_попадает_в_каждый_ход():
    провайдер = сделать()
    разбор = провайдер._разобрать(ответ())
    assert разбор.апстрим == "Alibaba"
    assert "@ Alibaba" in разбор.модель_факт, разбор.модель_факт


def тест_деньги_берутся_у_прослойки():
    разбор = сделать()._разобрать(ответ())
    assert разбор.деньги == 0.00123, "usage.cost проигнорирован"


def тест_кэш_и_размышление_разобраны():
    разбор = сделать()._разобрать(ответ())
    assert разбор.токены.кэш_чтение == 800
    # Вход без кэшированных: иначе он задваивается и доля кэша врёт.
    assert разбор.токены.вход == 200, разбор.токены.вход
    assert разбор.токены.размышление == 12


def тест_размышление_внутри_или_рядом_с_выходом():
    """Общего правила нет, и ошибка стоит половины счёта.

    Payload'ы настоящие, с круга ноль 2026-08-11. У xAI сумма сходится только
    если размышление прибавить к выходу, у OpenRouter — только если не
    прибавлять. Проверяем по арифметике самого вендора, а не по умолчанию.
    """
    from src.providers.xai import ПровайдерXAI

    xai = ПровайдерXAI(параметры=Параметры(), цены={}, журнал=None)
    отдельно = xai._токены({
        "prompt_tokens": 4741, "completion_tokens": 142, "total_tokens": 5050,
        "prompt_tokens_details": {"cached_tokens": 384},
        "completion_tokens_details": {"reasoning_tokens": 167},
    })
    assert отдельно.выход == 309, f"xai: выход {отдельно.выход}, ждали 142+167"
    assert отдельно.вход == 4357, "кэшированные не вычтены из входа"

    внутри = сделать()._токены({
        "prompt_tokens": 4258, "completion_tokens": 3017, "total_tokens": 7275,
        "prompt_tokens_details": {"cached_tokens": 0},
        "completion_tokens_details": {"reasoning_tokens": 2896},
    })
    assert внутри.выход == 3017, f"openrouter: выход {внутри.выход}, задвоили размышление"
    assert внутри.размышление == 2896


def тест_заголовки_только_ascii():
    """Персонажей зовут Курт и Ханна, а заголовки обязаны быть ASCII.

    Кириллица в заголовке роняет запрос не на сервере, а в клиенте — с
    невнятным «'ascii' codec can't encode», и до модели он не доходит вовсе.
    """
    import os

    from src.providers.xai import ПровайдерXAI

    # Ключ подставной, но обязательно латиницей: настоящие ключи такие и есть,
    # а кириллица здесь ловила бы саму пробу, а не заголовки провайдера.
    os.environ.setdefault("OPENROUTER_API_KEY", "test-key-0000")
    os.environ.setdefault("XAI_API_KEY", "test-key-0000")

    class Сессия(ПодложнаяСессия):
        агент = "Ханна"

    for провайдер in (сделать(),
                      ПровайдерXAI(параметры=Параметры(), цены={}, журнал=None)):
        for имя, значение in провайдер._заголовки(Сессия()).items():
            for кусок, что in ((имя, "имя"), (значение, "значение")):
                try:
                    кусок.encode("ascii")
                except UnicodeEncodeError:
                    raise AssertionError(
                        f"{провайдер.имя}: {что} заголовка {имя!r} не ASCII: {кусок!r}"
                    )


def тест_метка_агента_устойчива_и_различает():
    """На неё опирается липкость кэша: не совпадёт между кругами — кэш мимо."""
    from src.providers.общий import метка_агента

    assert метка_агента("Ханна") == метка_агента("Ханна"), "метка скачет между вызовами"
    assert метка_агента("Ханна") != метка_агента("Курт"), "разные агенты слиплись"
    метка_агента("Ханна").encode("ascii")


def тест_смена_апстрима_это_событие():
    события = []
    провайдер = сделать(журнал=lambda тип, **поля: события.append({"тип": тип, **поля}))

    провайдер._разобрать(ответ("Alibaba"))
    провайдер._разобрать(ответ("Alibaba"))       # тот же — второго события быть не должно
    провайдер._разобрать(ответ("DeepInfra"))     # чужой посреди прогона

    отметки = [с for с in события if с["тип"] == "апстрим"]
    assert len(отметки) == 2, f"событий {len(отметки)}, ждали 2: {отметки}"
    assert отметки[0]["первый"] is True and отметки[0]["апстрим"] == "Alibaba"
    assert отметки[1]["первый"] is False and отметки[1]["апстрим"] == "DeepInfra"

    расхождения = провайдер.добытые_расхождения
    assert any("сменился посреди прогона" in с for с in расхождения), расхождения


if __name__ == "__main__":
    провалов = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("тест_"):
            try:
                функция()
                print(f"  ok   {имя}")
            except AssertionError as ошибка:
                провалов += 1
                print(f"  ПЛОХО {имя}: {ошибка}")
    print("прослойка под замком" if not провалов else f"провалов: {провалов}")
    sys.exit(1 if провалов else 0)
