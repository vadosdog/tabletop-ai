#!/usr/bin/env python3
"""Тесты кубиков: python3 orchestrator/tests/test_dice.py"""

import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src.dice import Кубики, модификатор_сложности  # noqa: E402

КОНФИГ = json.loads((КОРЕНЬ / "config.json").read_text(encoding="utf-8"))


def тест_таблица_сложности():
    assert модификатор_сложности("очень легко") == (60, True)
    assert модификатор_сложности("Средне") == (20, True)
    assert модификатор_сложности("испытание") == (0, True)
    assert модификатор_сложности("тяжёлая") == (-20, True)
    assert модификатор_сложности("очень тяжело") == (-30, True)
    assert модификатор_сложности("трудная проверка") == (-10, True)
    # Неизвестная сложность не роняет прогон, но помечается.
    assert модификатор_сложности("невозможно") == (0, False)


def тест_цель_по_характеристике():
    к = Кубики(КОНФИГ, 1)
    б = к.бросить("Курт", "Сила воли", "трудно")
    assert б.база == 30 and б.модификатор == -10 and б.цель == 20
    assert б.характеристика == "Сила воли" and б.надбавка == 0


def тест_цель_по_навыку():
    к = Кубики(КОНФИГ, 1)
    # Восприятие стоит на Инициативе; у Ханны навык обученный, отсюда надбавка.
    б = к.бросить("Ханна", "Восприятие", "испытание")
    assert б.характеристика == "Инициатива" and б.база == 42
    assert б.надбавка == 10 and б.цель == 52

    # У Курта восприятие тоже в карточке, а обман — нет.
    необученный = к.бросить("Лизель", "Скрытность", "средне")
    assert необученный.характеристика == "Ловкость" and необученный.надбавка == 0
    assert необученный.цель == 41 + 20


def тест_бросок_за_персонажа_мира():
    к = Кубики(КОНФИГ, 1)
    # У Гретель Обман задан числом прямо в карточке — оно старше расчёта.
    б = к.бросить("Гретель", "Обман", "испытание")
    assert б.база == 45 and б.надбавка == 0 and б.цель == 45
    assert б.метки == []
    # Навыка без явного значения — считается по характеристике.
    по_характеристике = к.бросить("Гретель", "Скрытность", "средне")
    assert по_характеристике.характеристика == "Ловкость"


def тест_явная_база_от_мастера():
    к = Кубики(КОНФИГ, 1)
    б = к.бросить("Хозяин мельницы", "Обман", "средне", явная_база=45)
    assert б.цель == 65 and "база_от_мастера" in б.метки


def тест_нпс_без_карточки_помечается():
    к = Кубики(КОНФИГ, 1)
    б = к.бросить("Кто-то безымянный", "Обман", "средне")
    assert "нпс_без_карточки" in б.метки


def тест_неизвестный_навык_помечается():
    к = Кубики(КОНФИГ, 1)
    б = к.бросить("Курт", "Жонглирование", "средне")
    assert "неизвестный_навык" in б.метки
    assert б.цель == КОНФИГ["база_по_умолчанию"] + 20


def тест_уровни_успеха():
    к = Кубики(КОНФИГ, 1)
    б = к.бросить("Курт", "Боевые навыки", "средне")  # цель 65
    б.выпало = 54
    # Пересчёт вручную по формуле десятков: 65 → 6, 54 → 5.
    assert (б.цель // 10) - (54 // 10) == 1


def тест_автоматика():
    # 01–05 успех всегда, 96–100 провал всегда, даже против высокой цели.
    к = Кубики(КОНФИГ, 1)
    успехи = провалы = 0
    for зерно in range(400):
        к = Кубики(КОНФИГ, зерно)
        б = к.бросить("Лизель", "Обаяние", "очень тяжело")  # цель 62
        if б.выпало <= 5:
            assert б.успех and б.авто == "автоуспех" and б.уровни_успеха >= 0
            успехи += 1
        if б.выпало >= 96:
            assert not б.успех and б.авто == "автопровал" and б.уровни_успеха <= -1
            провалы += 1
    assert успехи and провалы, "за 400 зёрен автоматика ни разу не сработала"


def тест_дубль_на_обычной_проверке():
    # Вне боя дубль — тоже событие: выдающийся успех или фумбл.
    for зерно in range(300):
        к = Кубики(КОНФИГ, зерно)
        б = к.бросить("Курт", "Сила", "средне")
        if б.выпало in (11, 22, 33, 44, 55, 66, 77, 88, 99, 100):
            assert б.дубль
            assert ("дубль_успех" in б.метки) == б.успех
            assert "ДУБЛЬ" in б.кратко()
            return
    raise AssertionError("за 300 зёрен дубль ни разу не выпал")


def тест_воспроизводимость():
    первый = [Кубики(КОНФИГ, 777).бросить("Курт", "Сила", "средне").выпало for _ in range(1)]
    к = Кубики(КОНФИГ, 777)
    броски = [к.бросить("Курт", "Сила", "средне").выпало for _ in range(10)]
    к2 = Кубики(КОНФИГ, 777)
    броски2 = [к2.бросить("Курт", "Сила", "средне").выпало for _ in range(10)]
    assert броски == броски2 and броски[0] == первый[0]
    assert len(set(броски)) > 1, "генератор выдаёт одно и то же число"


if __name__ == "__main__":
    провалено = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("тест_"):
            try:
                функция()
                print(f"  ok   {имя}")
            except AssertionError as ошибка:
                провалено += 1
                print(f"  ПРОВАЛ {имя}: {ошибка}")
    print("все тесты кубиков прошли" if not провалено else f"провалено: {провалено}")
    sys.exit(1 if провалено else 0)
