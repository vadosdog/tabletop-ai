#!/usr/bin/env python3
"""Что делает прогон, когда игрок отказался: искусственный отказ на заглушке.

    python3 orchestrator/tests/test_отказ_в_прогоне.py

Ловля отказа в отдельности проверена в test_отказы.py. Здесь проверяется всё
остальное, что брифом требуется от прогона: отказ не повторяется молча, текст
отказа не утекает за стол, прогон не падает, персонаж считается промолчавшим,
а счётчик и цитата доходят до итога.
"""

import asyncio
import json
import sys
import tempfile
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src.combat import Боевка  # noqa: E402
from src.dice import Кубики  # noqa: E402
from src.logbook import Журнал, прочитать  # noqa: E402
from src.prompts import Промпты  # noqa: E402
from src.providers import base as провайдеры  # noqa: E402
from src.providers.stub import ПровайдерЗаглушка, СессияЗаглушка  # noqa: E402
from src.session import Прогон  # noqa: E402

КОНФИГ = json.loads((КОРЕНЬ / "config.json").read_text(encoding="utf-8"))

ТЕКСТ_ОТКАЗА = (
    "Как языковая модель, я не могу отыгрывать эту сцену: она описывает угрозу "
    "ребёнку. Предлагаю сменить направление истории."
)
ОТКАЗЧИК = "Ханна"


class СессияОтказчик(СессияЗаглушка):
    """Игрок, который отказывается на каждом ходу. Считаем обращения к нему."""

    обращений = 0

    async def отправить(self, текст: str):
        ответ = await super().отправить(текст)
        ответ.провайдер = "отказчик"
        if self.роль == "игрок" and self.агент == ОТКАЗЧИК:
            type(self).обращений += 1
            ответ.текст = ТЕКСТ_ОТКАЗА
            ответ.метки = ["отказ"]
        return ответ


class ПровайдерОтказчик(ПровайдерЗаглушка):
    имя = "отказчик"

    async def открыть(self, агент, системный_промпт, модель):
        роль = "судья" if агент.startswith("Судья") else (
            "мастер" if агент == "Мастер" else "игрок")
        сессия = СессияОтказчик(агент, роль, модель)
        self.сессии.append(сессия)
        return сессия


провайдеры.зарегистрировать("отказчик", ПровайдерОтказчик)


def прогнать() -> tuple[list[dict], Прогон]:
    конфиг = json.loads(json.dumps(КОНФИГ))
    конфиг["предел_кругов"] = 4
    конфиг["мастер"]["провайдер"] = "отказчик"
    for настройки_игрока in конфиг["игроки"].values():
        настройки_игрока["провайдер"] = "отказчик"

    временная = Path(tempfile.mkdtemp(prefix="нри-отказ-"))
    журнал = Журнал(временная / "лог.jsonl")
    промпты = Промпты((КОРЕНЬ / конфиг["документ"]).resolve(), КОРЕНЬ)
    кубики = Кубики(конфиг, конфиг["зерно"])
    прогон = Прогон(
        конфиг, промпты, журнал, кубики,
        {"отказчик": провайдеры.создать("отказчик")},
        Боевка(конфиг, кубики, КОРЕНЬ / "криты.json"),
    )

    async def гонка():
        await прогон.подготовить()
        await прогон.играть()
        await прогон.завершить()

    asyncio.run(гонка())
    журнал.закрыть()
    return прочитать(временная / "лог.jsonl"), прогон


СОБЫТИЯ, ПРОГОН = прогнать()
ХОДЫ = [е for е in СОБЫТИЯ if е["тип_события"] == "ход"]
ДОСТАВКИ = [е for е in СОБЫТИЯ if е["тип_события"] == "доставка"]
ИТОГ = [е for е in СОБЫТИЯ if е["тип_события"] == "итог"][0]


def тест_прогон_не_упал():
    """Отказ — не сбой. Круги идут дальше до своего предела."""
    assert ПРОГОН.остановка == "предел_кругов", ПРОГОН.остановка
    assert ПРОГОН.круг == 4


def тест_отказ_не_повторяется():
    """Ровно одно обращение на ход. Тихий ретрай спрятал бы самое интересное."""
    ходов = len([х for х in ХОДЫ if х["говорящий"] == ОТКАЗЧИК])
    assert СессияОтказчик.обращений == ходов, (
        f"обращений {СессияОтказчик.обращений}, ходов {ходов} — где-то повтор"
    )


def тест_отказ_записан_отдельным_событием():
    отказные = [х for х in ХОДЫ
                if х["говорящий"] == ОТКАЗЧИК and "отказ" in (х.get("метки") or [])]
    assert отказные, "ни один отказ не помечен"
    for ход in отказные:
        assert ход["видимость"] == "никому (отказ)"
        assert ТЕКСТ_ОТКАЗА[:40] in ход["текст"], "цитата не сохранена"


def тест_текст_отказа_не_утёк_за_стол():
    """Ни мастер, ни другие игроки не должны увидеть нравоучение."""
    for событие in СОБЫТИЯ:
        текст = событие.get("текст") or ""
        if событие.get("видимость") in ("всем", "только мастеру"):
            assert "языковая модель" not in текст, событие
    # Доставки текста не хранят, поэтому проверяем по сводам мастеру: длина
    # доставки от посредника не должна включать отказ.
    assert all(д["символов"] < 100_000 for д in ДОСТАВКИ)


def тест_счётчик_и_цитаты_дошли_до_итога():
    assert ИТОГ.get("отказов"), "в итоге нет счётчика отказов"
    цитаты = ИТОГ.get("отказы") or []
    assert цитаты, "в итоге нет цитат"
    for запись in цитаты:
        assert запись["кто"] == ОТКАЗЧИК
        assert запись["провайдер"] == "отказчик"
        assert "языковая модель" in запись["цитата"]


def тест_отказ_учтён_по_провайдеру():
    строка = (ИТОГ.get("по_провайдерам") or {}).get("отказчик") or {}
    assert строка.get("отказов"), "отказы не легли в счётчик провайдера"


if __name__ == "__main__":
    провалов = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("тест_"):
            try:
                функция()
                print(f"  ok   {имя}")
            except AssertionError as ошибка:
                провалов += 1
                print(f"  ПЛОХО {имя}: {ошибка}")
    print("отказы в прогоне обрабатываются верно" if not провалов
          else f"провалов: {провалов}")
    sys.exit(1 if провалов else 0)
