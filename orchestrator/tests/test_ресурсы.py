def тест_выбранное_число_читается_из_заявки():
    assert выбранное_значение("ТРАЧУ СУДЬБУ, беру 01 — рука не дрогнет.") == 1
    assert выбранное_значение("Трачу судьбу и выбираю 5") == 5
    # Не назвал — берём лучшее: он и так заплатил постоянным ресурсом.
    assert выбранное_значение("ТРАЧУ СУДЬБУ. Курт делает невозможное.") == 1
    # «200» на сотне не бывает: число не распознаётся вовсе, и заявка падает
    # в умолчание. Трактовать молчание в пользу игрока честнее, чем угадывать.
    assert выбранное_значение("Трачу судьбу, беру 200") == 1


def тест_порча_языка_ловит_подменённые_буквы():
    """Латинская буква внутри русского слова — глазом не видно, а это порча."""
    чисто = порча_языка("Ханна кивает и уходит в погреб.")
    assert not чисто["испорчено"], чисто

    подмена = порча_языка("Ханна кивaет и уходит в пoгреб.")
    assert подмена["испорчено"]
    assert len(подмена["смешанные_слова"]) == 2, подмена["смешанные_слова"]

    чужой = порча_языка("Ханна sparingly and quietly continues resting by the road.")
    assert чужой["испорчено"] and чужой["целиком_не_по_русски"]

    # Ложных срабатываний быть не должно: аббревиатура и одинокая латинская
    # буква — это не порча, а обычная запись.
    for безобидное in ("Он показал пункт a в бумаге.", "Курт смотрит на HP."):
        assert not порча_языка(безобидное)["испорчено"], безобидное


