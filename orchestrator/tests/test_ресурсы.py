#!/usr/bin/env python3
"""Судьба, Удача, Стойкость, Решимость: python3 orchestrator/tests/test_ресурсы.py

Главное, что здесь проверяется, — разница между «сказал, что тратит» и
«потратил». На её отсутствии сгорели два прошлых прогона: Удачи в коде не
было вовсе, игроки её «тратили», а судья засчитывал это за работу с
механикой и ставил высший балл.

Второе по важности — правило связи потолков: запас Удачи равен текущей
Судьбе, запас Решимости равен текущей Стойкости. Если реализация даёт
другое, это ошибка, и бриф говорит об этом прямо.
"""

import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src.combat import Боевка  # noqa: E402
from src.dice import Кубики  # noqa: E402
from src.parse import начисления_решимости, траты  # noqa: E402

КОНФИГ = json.loads((КОРЕНЬ / "config.json").read_text(encoding="utf-8"))
ИМЕНА = list(КОНФИГ["базовый_порядок"])


def боевка() -> Боевка:
    return Боевка(КОНФИГ, Кубики(КОНФИГ, 1), КОРЕНЬ / "криты.json")


def тест_стартовые_значения_и_связь_потолков():
    б = боевка()
    for имя in ИМЕНА:
        р = б.ресурсы(имя)
        assert (р["судьба"], р["удача"]) == (2, 2), (имя, р)
        assert (р["стойкость"], р["решимость"]) == (1, 1), (имя, р)
        # Потолок восполняемого равен постоянному — это и есть правило связи.
        assert р["удача_макс"] == р["судьба"], имя
        assert р["решимость_макс"] == р["стойкость"], имя


def тест_трата_судьбы_роняет_потолок_удачи():
    б = боевка()
    б.применить_судьбу("Курт", True)
    р = б.ресурсы("Курт")
    assert р["судьба"] == 1
    assert р["удача_макс"] == 1, "потолок Удачи не опустился вслед за Судьбой"
    assert р["удача"] <= 1, "текущая Удача осталась выше нового потолка"


def тест_трата_стойкости_роняет_потолок_решимости():
    б = боевка()
    итог = б.потратить_стойкость("Ансельм")
    assert итог["успех"]
    р = б.ресурсы("Ансельм")
    assert р["стойкость"] == 0
    assert р["решимость_макс"] == 0
    assert р["решимость"] == 0, "Решимость осталась выше обнулённого потолка"


def тест_больше_чем_есть_не_потратить():
    б = боевка()
    assert б.потратить("Ханна", "решимость")["успех"], "первая трата должна пройти"
    вторая = б.потратить("Ханна", "решимость")
    assert not вторая["успех"], "потрачено больше, чем было"
    assert "кончилась" in вторая["причина"]
    # Ресурс не ушёл в минус: отрицательный остаток врал бы в строке состояния.
    assert б.ресурсы("Ханна")["решимость"] == 0


def тест_решимость_не_поднимается_выше_потолка():
    б = боевка()
    полный = б.начислить_решимость("Лизель", 1)
    assert not полный["успех"] and полный["добавлено"] == 0, "начислили сверх потолка"

    б.потратить("Лизель", "решимость")
    вернули = б.начислить_решимость("Лизель", 5)
    assert вернули["добавлено"] == 1, "начислено больше, чем помещается"
    assert б.ресурсы("Лизель")["решимость"] == 1


def тест_решимость_снимает_дух_но_не_тело():
    """Порез и слепота силой воли не лечатся, страх и оглушение — да."""
    б = боевка()
    боец = б.лист("Курт")
    боец.состояния = ["сломлен", "оглушён", "кровотечение", "ослеплён"]
    снято = б.снять_состояния("Курт", ("сломлен", "оглушён"))
    assert set(снято) == {"сломлен", "оглушён"}, снято
    assert set(боец.состояния) == {"кровотечение", "ослеплён"}, боец.состояния


def тест_заявка_распознаётся_в_любом_падеже():
    assert траты("ТРАЧУ УДАЧУ и бью снова") == ["удача"]
    assert траты("Трачу Решимость, стискиваю зубы") == ["решимость"]
    assert траты("трачу стойкость — иначе конец") == ["стойкость"]
    # Дубли не множатся, порядок сохраняется.
    assert траты("Трачу удачу. Трачу решимость. Трачу удачу.") == ["удача", "решимость"]


def тест_разговор_про_удачу_не_заявка():
    """Иначе любое «повезло» спишет ресурс, которого игрок не тратил."""
    for текст in (
        "Курту сегодня не хватает удачи",
        "«Судьба к нам недобра», — говорит Ансельм",
        "Он полагается на удачу, а не на молот",
    ):
        assert траты(текст) == [], текст


def тест_тег_решимости_от_мастера():
    записи = начисления_решимости(
        "Сцена. [РЕШИМОСТЬ: Ханна, +1, вступилась за Йорга против патруля] Дальше.",
        ИМЕНА)
    assert len(записи) == 1
    assert записи[0]["имя"] == "Ханна"
    assert записи[0]["сколько"] == 1
    assert "Йорг" in записи[0]["причина"]


def тест_сержанту_дали_судьбу():
    """Бриф: чтобы он мог пережить то, чего не должен был."""
    assert КОНФИГ["персонажи_мира"]["Сержант"]["судьба"] == 1


def тест_у_каждого_игрока_есть_мотивация():
    """На ней держится возврат Решимости — без неё начислять не за что."""
    б = боевка()
    for имя in ИМЕНА:
        assert б.лист(имя).мотивация, f"у {имя} нет мотивации"


if __name__ == "__main__":
    провалов = 0
    for имя, функция in sorted(globals().items()):
        if имя.startswith("тест_"):
            try:
                функция()
                print(f"  ok   {имя}")
            except AssertionError as ошибка:
                провалов += 1
                print(f"  ПЛОХО {имя}: {ошибка}")
    print("ресурсы в порядке" if not провалов else f"провалов: {провалов}")
    sys.exit(1 if провалов else 0)
