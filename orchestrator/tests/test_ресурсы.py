#!/usr/bin/env python3
"""Судьба, Удача, Стойкость, Решимость: python3 orchestrator/tests/test_ресурсы.py

Главное, что здесь проверяется, — разница между «сказал, что тратит» и
«потратил». На её отсутствии сгорели два прошлых прогона: Удачи в коде не
было вовсе, игроки её «тратили», а судья засчитывал это за работу с
механикой и ставил высший балл.

Второе по важности — правило связи потолков: запас Удачи равен текущей
Судьбе, запас Решимости равен текущей Стойкости. Если реализация даёт
другое, это ошибка, и бриф говорит об этом прямо.
"""

import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from src.combat import Боевка  # noqa: E402
from src.dice import Кубики  # noqa: E402
from src.parse import (  # noqa: E402
    выбранное_значение, начисления_решимости, порча_языка, траты,
)

КОНФИГ = json.loads((КОРЕНЬ / "config.json").read_text(encoding="utf-8"))
ИМЕНА = list(КОНФИГ["базовый_порядок"])


def боевка() -> Боевка:
    return Боевка(КОНФИГ, Кубики(КОНФИГ, 1), КОРЕНЬ / "криты.json")


def тест_стартовые_значения_и_связь_потолков():
    б = боевка()
    for имя in ИМЕНА:
        р = б.ресурсы(имя)
        assert (р["судьба"], р["удача"]) == (2, 2), (имя, р)
        # Решимость пуста при потолке один: в третьем прогоне три начисления
        # мастера подряд сгорели, потому что копилка была полна с первого круга.
        assert (р["стойкость"], р["решимость"]) == (1, 0), (имя, р)
        # Потолок восполняемого равен постоянному — это и есть правило связи.
        assert р["удача_макс"] == р["судьба"], имя
        assert р["решимость_макс"] == р["стойкость"], имя


def тест_первое_начисление_решимости_ложится():
    """Ради этого стартовую Решимость и обнулили."""
    б = боевка()
    итог = б.начислить_решимость("Ханна", 1)
    assert итог["успех"] and итог["добавлено"] == 1, итог
    assert б.ресурсы("Ханна")["решимость"] == 1


def тест_судьба_даёт_выбрать_число_на_кубах():
    """Второе применение Судьбы: в безнадёжном положении игрок берёт число сам."""
    б = боевка()
    кубики = Кубики(КОНФИГ, 7)
    бросок = кубики.бросить("Курт", "Ловкость", "трудно")
    взято = кубики.подменить(бросок, 1, "выбрано_за_судьбу")

    assert взято.выпало == 1
    assert взято.успех, "01 обязан быть успехом"
    assert взято.авто == "автоуспех"
    assert "выбрано_за_судьбу" in взято.метки
    # Всё остальное от исходного броска сохранилось: цель, навык, номер.
    assert (взято.цель, взято.навык) == (бросок.цель, бросок.навык)

    итог = б.потратить_судьбу("Курт")
    assert итог["успех"]
    р = б.ресурсы("Курт")
    assert р["судьба"] == 1, "Судьба не списалась"
    assert р["удача_макс"] == 1, "потолок Удачи не упал вслед за Судьбой"
    assert р["удача"] <= 1, "Удача осталась выше нового потолка"
    # Беспамятства быть не должно: это применение не про смерть.
    assert not б.лист("Курт").без_сознания


def тест_подмена_пересчитывает_исход():
    """Иначе в лог уйдёт красивая единица с чужим успехом."""
    кубики = Кубики(КОНФИГ, 11)
    бросок = кубики.бросить("Лизель", "Обман", "трудно")
    for значение, ждём_успех in ((1, True), (100, False), (96, False)):
        взято = кубики.подменить(бросок, значение, "проба")
        assert взято.успех is ждём_успех, (значение, взято.успех)
    assert кубики.подменить(бросок, 100, "проба").дубль, "100 обязан быть дублем"


def тест_трата_судьбы_роняет_потолок_удачи():
    б = боевка()
    б.применить_судьбу("Курт", True)
    р = б.ресурсы("Курт")
    assert р["судьба"] == 1
    assert р["удача_макс"] == 1, "потолок Удачи не опустился вслед за Судьбой"
    assert р["удача"] <= 1, "текущая Удача осталась выше нового потолка"


def тест_трата_стойкости_роняет_потолок_решимости():
    б = боевка()
    итог = б.потратить_стойкость("Ансельм")
    assert итог["успех"]
