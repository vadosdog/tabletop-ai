# --- атака ----------------------------------------------------------------

def тест_попадание_и_урон():
    # Курт (БН 45, СБ 4, меч 4) бьёт Тварь (БН 40, ТБ 4, броня 1 везде).
    # Атака 12 → УУ +3; защита 38 → УУ +1; разница +2.
    б = боевка([12, 38])
    итог = б.атака("Курт", "Тварь", "меч")
    assert итог.попадание and итог.разница == 2
    assert итог.локация == "левая рука"          # 12 → 21
    assert итог.урон_до_брони == 4 + 4 + 2        # СБ + рейтинг + разница
    assert итог.защита == 4 + 1                   # ТБ цели + броня локации
    assert итог.ран_снято == 5
    assert б.лист("Тварь").раны == 15 - 5


def тест_промах_при_равной_разнице():
    # Оба выбросили одинаково: разница ноль — атака не проходит.
    б = боевка([32, 32])
    итог = б.атака("Курт", "Тварь", "меч")
    assert not итог.попадание and итог.разница == 0
    assert б.лист("Тварь").раны == б.лист("Тварь").раны_макс


def тест_броня_гасит_урон():
    # Лизель (СБ 2, нож 2) по Сержанту (ТБ 4, броня 1 на руке).
    # Разница +1 → урон 5, защита 5 → ноль ран. Броски не дубли, иначе крит.
    б = боевка([21, 50])
    итог = б.атака("Лизель", "Сержант", "нож")
    assert итог.попадание and итог.ран_снято == 0
    assert б.лист("Сержант").раны == б.лист("Сержант").раны_макс


