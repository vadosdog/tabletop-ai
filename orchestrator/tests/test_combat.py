def тест_смерть_ждёт_решения_игрока():
    # Крит в голову с броском 100 по таблице — смерть, но Судьбу тратит игрок.
    б = боевка([10, 90, 100])
    цель = б.лист("Лизель")
    цель.раны = 0
    итог = б.атака("Тварь", "Лизель", "когти")
    assert итог.локация == "голова" and итог.смерть
    assert итог.ждёт_судьбу, "скрипт не смеет решать за игрока"
    assert not цель.мёртв, "до ответа игрока персонаж не мёртв"

    сообщение = б.применить_судьбу("Лизель", True)
    assert "Судьбу" in сообщение and цель.судьба == 1
    assert цель.без_сознания and not цель.мёртв


def тест_отказ_от_судьбы_убивает():
    б = боевка([10, 90, 100])
    б.лист("Лизель").раны = 0
    б.атака("Тварь", "Лизель", "когти")
    б.применить_судьбу("Лизель", False)
    assert б.лист("Лизель").мёртв and б.счётчики["смертей"] == 1


def тест_счётчик_критов_отрывает_конечность():
    б = боевка([])
    цель = б.лист("Лизель")
    тб = цель.тб
    # Перебор критов в одну руку сверх бонуса Выносливости — рука потеряна.
    for _ in range(тб + 1):
        б.кубики.очередь.extend([12, 99, 30])
        цель.раны = 0
        б.атака("Тварь", "Лизель", "когти")
    assert "левая рука" in цель.потерянные_конечности


