КРИТЫ = КОРЕНЬ / "криты.json"


class КубикиПоСписку(Кубики):
    """Кидает то, что велено. Список кончился — дальше единицы."""

    def __init__(self, конфиг, броски):
        super().__init__(конфиг, зерно=0)
        self.очередь = list(броски)

    def подставной(self) -> int:
        self._номер += 1
        return self.очередь.pop(0) if self.очередь else 1


def боевка(броски) -> Боевка:
    return Боевка(КОНФИГ, КубикиПоСписку(КОНФИГ, броски), КРИТЫ)


# --- листы и формула ------------------------------------------------------

def тест_формула_ран():
    б = боевка([])
    # Контрольные цифры из брифа: если не сходится — ошибка в реализации.
