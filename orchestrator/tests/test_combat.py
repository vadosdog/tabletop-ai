def тест_размеры_и_талант():
    б = боевка([])
    характеристики = {"Сила": 40, "Выносливость": 40, "Сила воли": 30}   # 4, 4, 3
    assert б.раны_по_формуле(характеристики, "средний", {}) == 15
    assert б.раны_по_формуле(характеристики, "мелкий", {}) == 11
    assert б.раны_по_формуле(характеристики, "крошечный", {}) == 4
    assert б.раны_по_формуле(характеристики, "крохотный", {}) == 1
    assert б.раны_по_формуле(характеристики, "большой", {}) == 30
    assert б.раны_по_формуле(характеристики, "огромный", {}) == 60
    assert б.раны_по_формуле(характеристики, "чудовищный", {}) == 120
    # Выносливый добавляет ТБ за уровень.
    assert б.раны_по_формуле(характеристики, "средний", {"выносливый": 2}) == 15 + 8


